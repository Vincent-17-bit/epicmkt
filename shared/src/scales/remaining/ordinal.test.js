test("label: the fallback", () => {
  assert.deepEqual(ok(label, "  Heavy   duty "), { scale: "label", value: "Heavy duty" });
  assert.equal(ok(label, 5).value, "5");
  assert.equal(ok(label, "Kids\u0000 shirt").value, "Kids shirt");
  assert.equal(label.format(ok(label, "Heavy duty")), "Heavy duty");
  assert.equal(label.sizeKey(ok(label, "Heavy Duty")), "label:-:heavy-duty");
  assert.equal(label.sizeKey(ok(label, "heavy   duty")), label.sizeKey(ok(label, "Heavy Duty")));
  assert.equal(label.sizeKey(ok(label, "Size: L")).split(":").length, 3);
  assert.equal(label.toBase(ok(label, "x")), null);
  assert.deepEqual(["Size 10", "Size 2"].map((t) => ok(label, t)).sort(label.compare).map((v) => v.value), ["Size 2", "Size 10"]);
  assert.equal(ok(label, "Kids shirts, ages 3 to 12").value, "Kids shirts, ages 3 to 12");
  assert.equal(ok(label, "Ünïcode ✓ name").value, "Ünïcode ✓ name");
  no(label, ""); no(label, "   "); no(label, "x".repeat(41)); no(label, "!!!");
  assert.deepEqual(label.plausible("x", "y", ok(label, "Cotton")), { ok: true });
  assert.match(label.plausible("x", "y", ok(label, "12")).warn, /number/);
  assert.match(label.plausible("x", "y", ok(label, "A rather long label for a button")).warn, /long/);
  assert.equal(label.plausible("x", "y", { scale: "label", value: "" }).ok, false);
});
