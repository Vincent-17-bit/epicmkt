import { test } from "node:test";
import assert from "node:assert/strict";
import { count, portion, vehicleClass, compatModel, colorTemperature, ipRating, gauge, label } from "./ordinal.js";

const ok = (s, raw, ctx) => { const r = s.parse(raw, ctx); assert.equal(r.ok, true, `${s.id} ${JSON.stringify(raw)}: ${r.error}`); return r.value; };
const no = (s, raw, ctx) => { const r = s.parse(raw, ctx); assert.equal(r.ok, false, `${s.id} ${JSON.stringify(raw)} should be rejected`); assert.ok(r.error); };

test("count: set, pack, box, seater, gang, tier, copies, pieces", () => {
  assert.deepEqual(ok(count, "set of 4"), { scale: "count", system: "set", value: 4 });
  assert.deepEqual(ok(count, "Pack of 6"), { scale: "count", system: "pack", value: 6 });
  assert.equal(ok(count, "box of 12").system, "box");
  assert.deepEqual(ok(count, "3-seater"), { scale: "count", system: "seater", value: 3 });
  for (const t of ["3 seater", "3 seats", "3seater"]) assert.equal(ok(count, t).system, "seater", t);
  assert.deepEqual(ok(count, "2 gang"), { scale: "count", system: "gang", value: 2 });
  assert.equal(ok(count, "2-gang").system, "gang");
  assert.equal(ok(count, "3 tiers").system, "tier");
  assert.equal(ok(count, "12 copies").system, "copies");
  assert.equal(ok(count, "6 pack").system, "pack");
  assert.deepEqual(ok(count, "12 pcs"), { scale: "count", system: "pieces", value: 12 });
  assert.equal(ok(count, "x12").value, 12);
  assert.equal(ok(count, "12").system, "pieces");
  assert.equal(ok(count, 12, { system: "set" }).system, "set");
  assert.equal(ok(count, "4", { system: "seater" }).system, "seater");
  assert.deepEqual(ok(count, { system: "set", value: 4 }), { scale: "count", system: "set", value: 4 });
  const f = (t) => count.format(ok(count, t));
  assert.deepEqual([f("set of 4"), f("pack of 6"), f("box of 12"), f("3-seater"), f("2-gang"), f("1 tier"), f("3 tiers"), f("1 copy"), f("12 copies"), f("12 pcs")],
    ["Set of 4", "Pack of 6", "Box of 12", "3-seater", "2-gang", "1 tier", "3 tiers", "1 copy", "12 copies", "12 pcs"]);
  assert.equal(count.sizeKey(ok(count, "set of 4")), "count:set:4");
  assert.notEqual(count.sizeKey(ok(count, "set of 4")), count.sizeKey(ok(count, "pack of 4")));
  assert.ok(count.compare(ok(count, "3-seater"), ok(count, "4-seater")) < 0);
  assert.equal(count.toBase(ok(count, "set of 4")), 4);
  no(count, "0"); no(count, "2.5"); no(count, "-3"); no(count, "many"); no(count, ""); no(count, "30-seater"); no(count, "20 gang"); no(count, 4, { system: "dozen" });
  assert.deepEqual(count.plausible("sofa", "seats", ok(count, "3-seater")), { ok: true });
  assert.match(count.plausible("sofa", "seats", ok(count, "12-seater")).warn, /larger/);
  assert.match(count.plausible("x", "y", ok(count, "set of 1")).warn, /smaller/);
  assert.match(count.plausible("x", "y", ok(count, "8 gang")).warn, /larger/);
  assert.equal(count.plausible("x", "y", { scale: "count", system: "seater", value: 99 }).ok, false);
  assert.equal(count.plausible("x", "y", { scale: "count", system: "nope", value: 3 }).ok, false);
});
test("portion: size words and plate fractions", () => {
  assert.deepEqual(ok(portion, "Small"), { scale: "portion", system: "size", value: "small" });
  for (const [t, v] of [["medium", "regular"], ["standard", "regular"], ["BIG", "large"], ["family size", "family"]]) assert.equal(ok(portion, t).value, v, t);
  assert.deepEqual(ok(portion, "half plate"), { scale: "portion", system: "plate", value: "half" });
  assert.equal(ok(portion, "Full").value, "full");
  assert.equal(ok(portion, "quarter plate").system, "plate");
  assert.equal(portion.format(ok(portion, "half")), "Half plate");
  assert.equal(portion.format(ok(portion, "regular")), "Regular");
  assert.equal(portion.sizeKey(ok(portion, "half plate")), "portion:plate:half");
  assert.notEqual(portion.sizeKey(ok(portion, "large")), portion.sizeKey(ok(portion, "full")));
  assert.deepEqual(["large", "small", "regular"].map((t) => ok(portion, t)).sort(portion.compare).map((v) => v.value), ["small", "regular", "large"]);
  assert.deepEqual(["full", "half", "quarter"].map((t) => ok(portion, t)).sort(portion.compare).map((v) => v.value), ["quarter", "half", "full"]);
  assert.ok(portion.compare(ok(portion, "family"), ok(portion, "quarter")) < 0);
  assert.equal(portion.toBase(ok(portion, "half")), 0.5);
  no(portion, "huge"); no(portion, ""); no(portion, "3");
  assert.deepEqual(portion.plausible("restaurant", "portion", ok(portion, "large")), { ok: true });
  assert.equal(portion.plausible("restaurant", "portion", { scale: "portion", system: "size", value: "half" }).ok, false);
});
