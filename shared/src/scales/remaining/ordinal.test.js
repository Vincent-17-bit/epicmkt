test("compat-model: list from the product type", () => {
  const models = ["iPhone 13", "iPhone 13 Pro", { label: "Galaxy S21+" }, "Galaxy S21"];
  assert.deepEqual(ok(compatModel, "iphone 13", { models }), { scale: "compat-model", value: "iPhone 13" });
  assert.equal(ok(compatModel, "IPHONE-13-PRO", { models }).value, "iPhone 13 Pro");
  assert.equal(ok(compatModel, "galaxy s21 plus", { models }).value, "Galaxy S21+");
  assert.equal(ok(compatModel, "galaxy s21", { models }).value, "Galaxy S21");
  no(compatModel, "Pixel 8", { models });
  no(compatModel, "Pixel 8"); no(compatModel, "", { models }); no(compatModel, "!!!", { open: true }); no(compatModel, "x".repeat(61), { open: true });
  assert.equal(ok(compatModel, "Pixel 8", { models, open: true }).value, "Pixel 8");
  assert.equal(ok(compatModel, "  Tecno   Spark 10 ", { open: true }).value, "Tecno Spark 10");
  assert.equal(compatModel.sizeKey(ok(compatModel, "iPhone 13", { models })), "compat-model:-:iphone-13");
  assert.notEqual(compatModel.sizeKey(ok(compatModel, "Galaxy S21+", { models })), compatModel.sizeKey(ok(compatModel, "Galaxy S21", { models })));
  assert.equal(compatModel.sizeKey(ok(compatModel, "iphone 13", { open: true })), compatModel.sizeKey(ok(compatModel, "IPHONE  13", { open: true })));
  assert.equal(compatModel.sizeKey({ scale: "compat-model", value: "A: B" }).split(":").length, 3);
  assert.equal(compatModel.toBase(ok(compatModel, "iPhone 13", { models })), null);
  assert.deepEqual(["iPhone 13 Pro", "iPhone 13"].map((t) => ok(compatModel, t, { models })).sort(compatModel.compare).map((v) => v.value), ["iPhone 13", "iPhone 13 Pro"]);
  assert.equal(compatModel.format(ok(compatModel, "iphone 13", { models })), "iPhone 13");
  assert.deepEqual(compatModel.plausible("phone-repair", "model", ok(compatModel, "iPhone 13", { models })), { ok: true });
  assert.match(compatModel.plausible("x", "y", { scale: "compat-model", value: "A very long model name that goes on and on" }).warn, /long/);
  assert.equal(compatModel.plausible("x", "y", { scale: "compat-model", value: "???" }).ok, false);
});
