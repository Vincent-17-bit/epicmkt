// Sample items for the conformance suite (Prompt 11.4). Everything is generated from the type or the category itself, so a new
// type or category is covered the day it is added and nobody has to write a fixture for it. Nothing here runs at import time.

import { buildDetail, grid } from "../contracts/fixtures/build.js";
import { rowChoices } from "../specRules/labels.js";

const letter = (i) => String.fromCharCode(65 + i);

/** Two values for an axis: the type's own suggestions when it has them, else "Sample A" and "Sample B". */
export const sampleValues = (axis) => {
  const own = (axis.suggested ?? []).slice(0, 2).map((s) => ({ id: s.id, label: s.label }));
  return own.length === 2 ? own : [0, 1].map((i) => ({ id: `sample-${letter(i).toLowerCase()}`, label: `Sample ${letter(i)}` }));
};

/** A believable answer for one spec row, whatever its input kind. */
export const sampleSpecValue = (row) => {
  const choices = rowChoices(row);
  if (choices?.length) return choices[0];
  if (row.input === "number") return "1";
  if (row.input === "boolean") return "Yes";
  if (row.input === "dimension") return "10 cm";
  return "Sample";
};

/** The sample item for a product type: every axis with two values, a price for every combination, every field the type allows. */
export function sampleSpecForType(type) {
  const plain = (type.axes ?? []).map((a) => ({ key: a.key, label: a.label, display: a.display, values: sampleValues(a) }));
  // A dependent axis lists, for every value of the axis it depends on, which of its own values may go with it (here: both).
  const axes = plain.map((axis, i) => {
    const parent = (type.axes ?? [])[i].dependsOn;
    const above = plain.find((x) => x.key === parent);
    return above ? { ...axis, dependsOn: { axis: parent, allowed: Object.fromEntries(above.values.map((v) => [v.id, axis.values.map((x) => x.id)])) } } : axis;
  });
  const fields = type.variantFields ?? [];
  const items = type.itemFields ?? [];
  let n = 0;
  const spec = {
    id: `cf-${type.id}`,
    productType: type.id,
    name: `Sample ${type.name}`,
    brand: null,
    hue: 200,
    unit: type.unit ?? null,
    description: `Generated by the conformance suite for ${type.name}.`,
    highlights: [],
    specs: (type.specRows ?? []).filter((r) => r.level !== "optional").map((r) => ({ label: r.label, value: sampleSpecValue(r) })),
    axes
  };
  if (items.includes("priceTiers")) spec.priceTiers = [{ minQty: 1, maxQty: 9, unitPrice: 100 }, { minQty: 10, maxQty: null, unitPrice: 80 }];
  if (items.includes("quantity")) spec.quantity = { min: 1, step: 1, unit: type.unit ?? "unit" };
  if (items.includes("dimensions")) spec.dimensions = { length: 10, width: 10, height: 10, unit: "cm" };
  if (axes.length) {
    spec.variants = grid(axes, () => ({
      price: 1000 + 100 * n++,
      ...(fields.includes("weightGrams") && { weightGrams: 100 }),
      ...(fields.includes("dimensions") && { dimensions: { length: 10, width: 10, height: 10, unit: "cm" } })
    }));
  } else {
    spec.price = 1000;
  }
  return spec;
}

export const sampleItemForType = (type) => buildDetail(sampleSpecForType(type), 0);

/** One answer for a category field, by its kind. */
export function sampleFieldValue(field) {
  switch (field.type) {
    case "number": return 1;
    case "price": return 1000;
    case "boolean": return true;
    case "select": return field.options?.[0] ?? null;
    case "multiselect": return field.options?.length ? [field.options[0]] : [];
    case "timerange": return { from: "08:00", to: "17:00" };
    case "url": return "https://example.com";
    case "image": return "https://example.com/sample.jpg";
    case "itemlist": return [{ name: "Sample", price: 1000 }];
    default: return "Sample";
  }
}

/** A shop's answers for a category: every field it asks for. */
export const sampleAnswersForCategory = (category) => Object.fromEntries((category.keyFields ?? []).map((f) => [f.key, sampleFieldValue(f)]));

/** An item with no product type and no options, the shape every category can always sell. */
export const sampleLegacyItem = (category) => buildDetail({
  id: `cf-legacy-${category.id}`,
  productType: null,
  name: `Sample item for ${category.name}`,
  description: "Generated by the conformance suite.",
  hue: 30,
  price: 1000,
  specs: []
}, 0);
