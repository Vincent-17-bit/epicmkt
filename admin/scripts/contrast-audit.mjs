// Audits every text/background and UI-component token pair in theme.css against WCAG 2.2 AA.
//   node scripts/contrast-audit.mjs            print failures, exit 1 if any
//   node scripts/contrast-audit.mjs --write    also (re)generate docs/admin-contrast.md from the live tokens
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { audit, parseTokens } from "../src/lib/contrast.js";

const here = dirname(fileURLToPath(import.meta.url));
const css = readFileSync(resolve(here, "../src/styles/theme.css"), "utf8");
const themes = ["light", "dark"];
const results = Object.fromEntries(themes.map((t) => [t, audit(css, t)]));
const all = themes.flatMap((t) => results[t]);
const failing = all.filter((r) => !r.pass);

for (const r of failing) console.log(`FAIL ${r.theme.padEnd(5)} ${r.fg} on ${r.bg}: ${r.ratio.toFixed(2)} (needs ${r.min}) ${r.note}`);
console.log(`${all.length - failing.length}/${all.length} pair checks pass`);

if (process.argv.includes("--write")) {
  const label = (r) => `\`${r.fg}\` on \`${r.bg}\`${r.note ? ` (${r.note})` : ""}`;
  const rows = results.light.map((l, i) => {
    const d = results.dark[i];
    const mark = (r) => `${r.ratio.toFixed(2)}${r.pass ? "" : " ✗"}`;
    return `| ${label(l)} | ${l.kind === "text" ? "Text" : "UI / graphic"} | ${l.min}:1 | ${mark(l)} | ${mark(d)} |`;
  });
  const tokens = { light: parseTokens(css, "light"), dark: parseTokens(css, "dark") };
  const doc = `# Admin colour contrast (WCAG 2.2 AA)

Generated by \`npm run check:a11y\` (\`node scripts/contrast-audit.mjs --write\`) from the live tokens in
\`admin/src/styles/theme.css\`. Do not edit the table by hand: change a token and re-run. The same pair list is
enforced by \`src/theme/contrast.ui.test.js\`, so a failing pair fails \`npm run test:ui\`.

**Result: ${all.length - failing.length} of ${all.length} pair checks pass (${results.light.length} pairs x 2 themes).**${failing.length ? ` ${failing.length} fail; see rows marked ✗.` : ""}

Thresholds: text 4.5:1 (1.4.3); focus indicators, form-field borders, icons and chart marks 3:1 (1.4.11, 2.4.11).
Translucent backgrounds (the \`*-tint\` tokens) are composited over the surface they sit on before measuring.

| Pair | Kind | Needs | Light | Dark |
| --- | --- | --- | --- | --- |
${rows.join("\n")}

## Exempt on purpose

| Item | Why it is not held to a ratio |
| --- | --- |
| Disabled controls (\`:disabled\`, reduced opacity) | WCAG 1.4.3 and 1.4.11 exempt inactive components. Disabled state is also conveyed by the \`disabled\` attribute, not by colour alone. |
| \`--border\` on cards, panels, table rules, dividers | Decorative separation; the content inside is identified by its own text. Form fields use \`--border-control\` (${tokens.light["border-control"]} light, ${tokens.dark["border-control"]} dark), which is held to 3:1. |
| Outlined and filled buttons | The text label identifies the control; 1.4.11 only requires boundary contrast where the boundary is the sole identifier. Label text is checked above. |
| Skeleton shimmer, avatar and ring backgrounds | Decorative; meaning is carried by adjacent text or an accessible name. |

## Beyond the token table

- **Real-browser axe sweep** (axe-core, tags wcag2a, wcag2aa, wcag21a, wcag21aa, wcag22aa, best-practice) over 17 admin pages,
  both themes, at 1280 px and 390 px wide: zero \`color-contrast\` violations. jsdom cannot compute colour, so this check
  runs in Chromium and is not part of \`npm run test:ui\`.
- **Focus visibility:** every keyboard stop on Command Center, Businesses, Settings, Messages, Payments and Moderation, in
  both themes (440 stops), shows an outline or ring. The ring colour is \`--primary-text\`, held to 3:1 on every surface above.
`;
  const out = resolve(here, "../../docs/admin-contrast.md");
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, doc);
  console.log(`wrote ${out}`);
}
process.exitCode = failing.length ? 1 : 0;
