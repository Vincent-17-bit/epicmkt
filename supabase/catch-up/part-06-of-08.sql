-- 3. Products by id, in the products_snapshot shape --------------------------------------------------------------------------
-- The same item columns, store columns and running flash sale as products_snapshot (as patched up to 0110), plus the search
-- facts of 0127, for a given list of ids, in that order. Reads the public views, so an id that is not public is simply absent.
-- `i.id = any(v_ids)` is a plain filter (uuid equality is leakproof), so it reaches the index on items even through the view.
create or replace function public.products_by_ids(p_ids uuid[]) returns jsonb
language plpgsql stable security definer set search_path = public set statement_timeout = '8s' as $$
declare
  -- A plain variable, not an expression: only a bare value reaches through the security_barrier view to the index (an
  -- expression such as p_ids[1:3000] is evaluated after the view, row by row, over every public item).
  v_ids uuid[] := coalesce(p_ids[1:3000], '{}'::uuid[]);
  v_shops uuid[];
  v_out jsonb;
begin
  -- The stores, as a plain list for the same reason (a join to the list of items would be checked against every store).
  select coalesce(array_agg(distinct i.business_id), '{}') into v_shops from public.items i where i.id = any(v_ids);

  with wanted as (
    select u.id, min(u.n) as n
    from unnest(v_ids) with ordinality as u(id, n)
    group by u.id
  ), kept as (
    select w.n, i.*
    from (
      select i.id, i.business_id, i.name, left(i.description, 160) as description, i.section, i.price, i.price_type,
             i.unit, i.availability, i.stock_left, i.created_at, i.image_paths ->> 0 as image_path, i.brand, i.price_min, i.price_high,
             i.has_options, i.option_count, i.department_id, i.product_type_id, i.has_3d, nullif(i.video_paths, '[]'::jsonb) as video_paths
      from public.public_items i
      where i.id = any(v_ids)
    ) i
    join wanted w on w.id = i.id
  )
  select jsonb_build_object(
    'items', coalesce((
      select jsonb_agg(to_jsonb(x) - 'n' order by x.n)
      from (
        select k.n, k.id, k.business_id, k.name, k.description, k.section, k.price, k.price_type, k.unit, k.availability, k.stock_left,
               k.created_at, k.image_path, k.brand, k.video_paths, public.item_size_values_public(k.id) as size_values, k.price_min,
               k.price_high as price_max, k.price_min < k.price_high as has_price_range, k.has_options, k.option_count, k.department_id,
               k.product_type_id, k.has_3d,
               f.id as sale_id, f.sale_price, f.starts_at as sale_starts_at, f.ends_at as sale_ends_at, f.headline as sale_headline
        from kept k
        left join lateral (
          select s.id, s.sale_price, s.starts_at, s.ends_at, s.headline
          from public.public_flash_sales s
          where s.item_id = k.id
          order by s.sale_price asc, s.id
          limit 1
        ) f on true
      ) x), '[]'::jsonb),
    'businesses', coalesce((
      select jsonb_agg(to_jsonb(b))
      from (
        select id, slug, name, plan_key, verification_level, category_id, town, county, hours, exceptions, timezone
        from public.public_businesses
        where id = any(v_shops)
      ) b), '[]'::jsonb),
    'facts', coalesce((
      select jsonb_object_agg(it.id, f.facts)
      from public.items it
      cross join lateral (
        select public.item_search_facts(it.specs, it.highlights, it.short_description, it.option_axes)
               || jsonb_strip_nulls(jsonb_build_object('productTypeId', it.product_type_id, 'departmentId', it.department_id)) as facts
      ) f
      where it.id in (select id from kept) and f.facts <> '{}'::jsonb
    ), '{}'::jsonb)
  ) into v_out;
  return v_out;
end $$;

-- 4. Search ------------------------------------------------------------------------------------------------------------------
-- Spelling: each word no known word starts with becomes the closest known word (same first letter, a few edits apart, the most
-- common on a tie): "mlik" -> "milk", "samsng" -> "samsung", "panadool" -> "panadol". Words the dictionary knows stay as typed.
-- The dictionary is small, so this is a handful of index lookups. Before the first refresh nothing is changed.
create or replace function public.search_correct_words(p_tokens text[]) returns text[]
language sql stable security definer set search_path = public, extensions set statement_timeout = '2s' as $$
  select coalesce(array_agg(coalesce(x.fix, x.t) order by x.n), '{}'::text[])
  from (
    select u.t, u.n,
      case when char_length(u.t) < 3 or u.t ~ '^[0-9]+$'
             or exists (select 1 from public.search_terms s where s.key like u.t || '%' and s.kind in ('phrase', 'brand', 'query', 'section'))
        then null
        else (
          select s.key
          from public.search_terms s
          where s.kind in ('phrase', 'brand') and s.key like left(u.t, 1) || '%' and s.key not like '% %'
            and abs(char_length(s.key) - char_length(u.t)) <= 2
            and levenshtein(s.key, u.t) <= case when char_length(u.t) <= 4 then 2 when char_length(u.t) <= 7 then 2 else 3 end
          order by levenshtein(s.key, u.t), s.weight desc, s.key
          limit 1
        )
      end as fix
    from unnest(coalesce(p_tokens, '{}'::text[])) with ordinality as u(t, n)
  ) x
$$;

-- The ids of the public items matching every word (as a prefix), best first, and how many were looked at (at most 10,000).
-- MATERIALIZED makes the full-text index drive the query: the planner otherwise starts from the stores and reads every item of
-- every store. Score: the query is the whole name, starts it, is a whole word of it, is in it; then how many of the words are
-- in the name (not only the brand or section); then newer.
create or replace function public.search_item_ids(p_tokens text[], p_limit integer, out ids uuid[], out seen integer)
language plpgsql stable security definer set search_path = public, extensions set statement_timeout = '5s' as $$
declare
  v_query tsquery := public.search_tsquery(p_tokens);
  v_phrase text := array_to_string(p_tokens, ' ');
begin
  ids := '{}';
  seen := 0;
  if v_query is null then
    return;
  end if;
  with m as materialized (
    select i.id, i.business_id, i.created_at, i.name, i.brand, i.section
    from public.items i
    where public.item_search_doc(i.name, i.brand, i.section) @@ v_query
      and public.item_is_public(i.visible, i.draft, i.hidden_by_admin, i.removed_by_admin, i.availability)
    limit 20000
  ), shops as materialized (
    -- The visible stores once, hashed, instead of one lookup per matching item.
    select b.id from public.businesses b where public.business_is_visible(b)
  ), hits as (
    select m.*, public.search_key(m.name) as name_key
    from m
    join shops on shops.id = m.business_id
    limit 10000
  )
  select coalesce(array_agg(s.id order by s.score desc, s.created_at desc, s.id), '{}'), count(*)
  into ids, seen
  from (
    select h.id, h.created_at,
           (case when h.name_key = v_phrase then 6
                 when h.name_key like v_phrase || '%' then 4
                 when ' ' || h.name_key || ' ' like '% ' || v_phrase || ' %' then 3
                 when h.name_key like '%' || v_phrase || '%' then 2
                 else 0 end)
           -- words found in the name itself (not only in the brand or section) count for more
           + 2.0 * (select count(*) from unnest(p_tokens) t where ' ' || h.name_key like '% ' || t || '%') / greatest(cardinality(p_tokens), 1) as score
    from hits h
  ) s;
  ids := coalesce(ids[1:greatest(coalesce(p_limit, 1000), 1)], '{}');
end $$;

-- { items, businesses, facts } as products_by_ids, plus matched (how many matched, up to 10,000), truncated (more exist than
-- were looked at) and corrected (the query actually searched, when a misspelling was corrected; else null).
create or replace function public.search_product_candidates(p_query text, p_limit integer default 600) returns jsonb
language plpgsql stable security definer set search_path = public, extensions set statement_timeout = '6s' as $$
declare
  v_tokens text[] := public.search_query_tokens(p_query);
  v_limit integer := least(greatest(coalesce(p_limit, 600), 1), 3000);
  v_ids uuid[];
  v_seen integer;
  v_fixed text[];
  v_corrected text := null;
begin
  if cardinality(v_tokens) = 0 then
    return jsonb_build_object('items', '[]'::jsonb, 'businesses', '[]'::jsonb, 'facts', '{}'::jsonb, 'matched', 0, 'truncated', false, 'corrected', null);
  end if;
  select r.ids, r.seen into v_ids, v_seen from public.search_item_ids(v_tokens, v_limit) r;
  if v_seen = 0 then
    v_fixed := public.search_correct_words(v_tokens);
    if v_fixed is distinct from v_tokens then
      select r.ids, r.seen into v_ids, v_seen from public.search_item_ids(v_fixed, v_limit) r;
      if v_seen > 0 then
        v_corrected := array_to_string(v_fixed, ' ');
      end if;
    end if;
  end if;
  return public.products_by_ids(v_ids)
    || jsonb_build_object('matched', v_seen, 'truncated', v_seen >= 10000, 'corrected', v_corrected);
end $$;

-- A picture, price and store for a term (the trending list): the newest public item it finds that has a picture, among its first
-- 2,000 matches.
create or replace function public.search_example_item(p_term text)
returns table (item_id uuid, label text, slug text, image text, price numeric)
language sql stable security definer set search_path = public, extensions set statement_timeout = '2s' as $$
  with m as materialized (
    select i.id, i.name, i.business_id, coalesce(i.price_min, i.price) as price, i.created_at
    from public.items i
    where public.item_search_doc(i.name, i.brand, i.section) @@ public.search_tsquery(public.search_query_tokens(p_term))
      and public.item_is_public(i.visible, i.draft, i.hidden_by_admin, i.removed_by_admin, i.availability)
    limit 2000
  )
  select m.id, m.name, b.slug,
         (select x.path from public.item_media x where x.item_id = m.id and x.kind = 'image' order by x.sort, x.created_at, x.id limit 1),
         m.price
  from m
  join public.businesses b on b.id = m.business_id
  where public.business_is_visible(b)
  order by exists (select 1 from public.item_media x where x.item_id = m.id and x.kind = 'image') desc, m.created_at desc, m.id
  limit 1
$$;

-- 5. Background refreshes --------------------------------------------------------------------------------------------------------
create or replace function public.refresh_top_searches() returns integer
language plpgsql volatile security definer set search_path = public, extensions set statement_timeout = '60s' as $$
declare
  v_rows integer;
begin
  -- Long-run popularity first (the dictionary weights "query" suggestions with it).
  update public.search_query_stats set score = score * 0.97 where score > 0.01;
  delete from public.search_query_stats where score <= 0.01 and last_seen < now() - interval '30 days';
  insert into public.search_query_stats as s (term, score, last_seen)
  select e.term, count(distinct e.client_hash), max(e.at)
  from public.search_events e
  where e.at > now() - interval '1 hour'
    and not exists (select 1 from public.search_blocklist b where position(b.term in e.term) > 0)
  group by e.term
  on conflict (term) do update set score = s.score + excluded.score, last_seen = greatest(s.last_seen, excluded.last_seen);

  -- Trending: the same rule as top_searches (0039), 24 hours, at least 3 different searchers.
  delete from public.search_top_hourly where true;
  insert into public.search_top_hourly (rank, term, searches, hot, item_id, label, slug, image, price, computed_at)
  select t.rn, t.term, t.searches, t.hot, x.item_id, x.label, x.slug, x.image, x.price, now()
  from (
    select row_number() over (order by count desc, term)::smallint as rn, term, count as searches, hot
    from public.top_searches(20)
  ) t
  left join lateral public.search_example_item(t.term) x on true;
  get diagnostics v_rows = row_count;
  return v_rows;
end $$;

-- Rebuilds the dictionary in one transaction (readers see the old one until it commits). Bounded: at most p_limit product words
-- and phrases, the most common first. On a catalogue of millions this is a background job of seconds to a few minutes.
create or replace function public.refresh_search_terms(p_limit integer default 60000) returns integer
language plpgsql volatile security definer set search_path = public, extensions set statement_timeout = '300s' as $$
declare
  v_limit integer := least(greatest(coalesce(p_limit, 60000), 100), 500000);
  v_rows integer;
begin
  -- No indexes on the scratch copy: every insert below is already one row per (kind, key).
  create temporary table if not exists pg_temp.search_terms_next (like public.search_terms including defaults) on commit drop;
  truncate pg_temp.search_terms_next;

  -- Product words and phrases. For "Brookside Fresh Milk 500ml": the phrases a name starts with ("brookside", "brookside fresh",
  -- "brookside fresh milk") and every word of it that has a letter and 3+ characters ("fresh", "milk"), so "mil" offers "milk"
  -- even when no name starts with it. Weight: how many live products carry it. Example item: the newest one with a picture.
  -- MATERIALIZED: each name is normalised once (inlined, the planner would redo it for every phrase and every sort step).
  with named as materialized (
    -- stamp: items with a picture first, then the newest (the example item is the greatest stamp)
    select i.id,
           (case when exists (select 1 from public.item_media m where m.item_id = i.id and m.kind = 'image') then '1' else '0' end)
             || to_char(i.created_at at time zone 'UTC', 'YYYYMMDDHH24MISSUS') as stamp,
           string_to_array(public.search_key(i.name), ' ') as k
    from public.items i
    join (select b.id from public.businesses b where public.business_is_visible(b)) shops on shops.id = i.business_id
    where public.item_is_public(i.visible, i.draft, i.hidden_by_admin, i.removed_by_admin, i.availability)
  ), keys as (
    select n.id, n.stamp, array_to_string(n.k[1:h], ' ') as key
    from named n, generate_series(1, least(3, coalesce(cardinality(n.k), 0))) h
    union
    select n.id, n.stamp, word
    from named n, unnest(n.k) word
    where char_length(word) >= 3 and word ~ '[a-z]'
      -- joining words and units say nothing about what a product is (the same list as client/src/lib/suggest.js)
      and word not in ('and', 'the', 'for', 'with', 'from', 'pcs', 'pack', 'set', 'new', 'per', 'pieces', 'piece', 'size', 'free',
                       'min', 'mins', 'hrs', 'hour', 'hours', 'ltr', 'litre', 'litres', 'liter', 'liters', 'inch', 'inches', 'kgs', 'gms', 'gram', 'grams')
  )
  insert into pg_temp.search_terms_next (kind, key, label, ref, slug, price, weight)
  select 'phrase', g.key, g.key, split_part(g.newest, ' ', 2), null, null, g.n
  from (
    select key, count(*) as n, max(stamp || ' ' || id::text) as newest
    from keys
    where char_length(key) between 2 and 80
    group by key
    order by count(*) desc, key
    limit v_limit
  ) g;

  -- The example item of each phrase: its name, store, lowest price and first picture.
  update pg_temp.search_terms_next t
     set label = i.name, slug = b.slug, price = coalesce(i.price_min, i.price),
         image = (select m.path from public.item_media m where m.item_id = i.id and m.kind = 'image' order by m.sort, m.created_at, m.id limit 1)
    from public.items i
    join public.businesses b on b.id = i.business_id
   where t.kind = 'phrase' and i.id = t.ref::uuid;

  with labelled as materialized (
    select nullif(btrim(i.brand), '') as brand, nullif(btrim(i.section), '') as section
    from public.items i
    join (select b.id from public.businesses b where public.business_is_visible(b)) shops on shops.id = i.business_id
    where public.item_is_public(i.visible, i.draft, i.hidden_by_admin, i.removed_by_admin, i.availability)
      and (nullif(btrim(i.brand), '') is not null or nullif(btrim(i.section), '') is not null)
  ), brands as (
    select public.search_key(brand) as key, min(brand) as label, count(*) as n from (select brand from labelled where brand is not null) x group by brand
  ), sections as (
    select public.search_key(section) as key, min(section) as label, count(*) as n from (select section from labelled where section is not null) x group by section
  )
  insert into pg_temp.search_terms_next (kind, key, label, weight)
  select kind, key, min(label), sum(n)
  from (
    (select 'brand' as kind, key, label, n from brands where char_length(key) between 2 and 80)
    union all
    (select 'section', key, label, n from sections where char_length(key) between 2 and 80)
  ) x
  group by kind, key;

  insert into pg_temp.search_terms_next (kind, key, label, ref, weight)
  select distinct on (public.search_key(pb.name)) 'store', public.search_key(pb.name), pb.name, pb.slug,
         case when pb.plan_key = 'premium' then 3 else 1 end
  from public.public_businesses pb
  where char_length(public.search_key(pb.name)) between 1 and 80
  order by public.search_key(pb.name), (pb.plan_key = 'premium') desc, pb.created_at desc;

  insert into pg_temp.search_terms_next (kind, key, label, ref, weight)
  select distinct on (public.search_key(c.name)) 'category', public.search_key(c.name), c.name, c.id, 100
  from public.categories c
  where c.active and char_length(public.search_key(c.name)) between 1 and 80
  order by public.search_key(c.name), c.sort;

  -- What people actually typed, the strongest signal there is. Blocklisted terms never come back.
  insert into pg_temp.search_terms_next (kind, key, label, weight)
  select distinct on (public.search_key(s.term)) 'query', public.search_key(s.term), s.term, s.score * 25
  from public.search_query_stats s
  where s.score >= 0.5 and char_length(public.search_key(s.term)) between 2 and 80
    and not exists (select 1 from public.search_blocklist b where position(b.term in s.term) > 0)
  order by public.search_key(s.term), s.score desc;

  delete from public.search_terms where true;
  insert into public.search_terms (kind, key, label, ref, slug, image, price, weight, refreshed_at)
  select kind, key, label, ref, slug, image, price, weight, now() from pg_temp.search_terms_next
  on conflict (kind, key) do nothing;
  get diagnostics v_rows = row_count;
  return v_rows;
end $$;

-- 6. Suggestions while typing -------------------------------------------------------------------------------------------------
-- { terms: [{ label }], products: [{ id, name, slug, image, price }], stores: [{ label, slug }], categories: [{ label, id }],
--   corrected } or NULL when the dictionary has never been built (the caller then uses its own fallback).
-- Tiers: the whole text starts with what was typed (3), a word in it does (2), it looks like it (1, 4+ letters). Two letters
-- only ever match "starts with", so "mi" is one short index range scan. Nothing at all: the last word is spelled-corrected
-- ("mlik" -> "milk") and `corrected` says what was shown instead.
create or replace function public.search_suggest(p_prefix text, p_limit integer default 8) returns jsonb
language plpgsql stable security definer
set search_path = public, extensions
set statement_timeout = '2s'
set pg_trgm.similarity_threshold = '0.35' as $$
declare
  v_q text := public.search_key(left(coalesce(p_prefix, ''), 60));
  v_limit integer := least(greatest(coalesce(p_limit, 8), 1), 12);
  v_corrected text := null;
  v_fixed text;
  v_out jsonb;
begin
  if char_length(v_q) < 2 then
    return jsonb_build_object('terms', '[]'::jsonb, 'products', '[]'::jsonb, 'stores', '[]'::jsonb, 'categories', '[]'::jsonb, 'corrected', null);
  end if;
  if not exists (select 1 from public.search_terms limit 1) then
    return null;
  end if;
  if char_length(v_q) >= 3 and not exists (select 1 from public.search_terms t where t.key like v_q || '%')
     and not exists (select 1 from public.search_terms t where t.key like '%' || v_q || '%' and (' ' || t.key) like '% ' || v_q || '%') then
    v_fixed := array_to_string(public.search_correct_words(string_to_array(v_q, ' ')), ' ');
    if v_fixed is distinct from v_q then
      v_corrected := v_fixed;
      v_q := v_fixed;
    end if;
  end if;

  with starts as (
    select t.*, 3 as tier from public.search_terms t where t.key like v_q || '%'
    order by t.weight desc, char_length(t.key)
    limit 400
  ), words as (
    select t.*, 2 as tier from public.search_terms t
    where char_length(v_q) >= 3 and t.key like '%' || v_q || '%' and (' ' || t.key) like '% ' || v_q || '%' and t.key not like v_q || '%'
    order by t.weight desc
    limit 200
  ), fuzzy as (
    select t.*, 1 as tier from public.search_terms t
    where char_length(v_q) >= 4 and t.key % v_q and t.key not like '%' || v_q || '%'
    order by similarity(t.key, v_q) desc, t.weight desc
    limit 60
  ), hits as (
    select * from starts union all select * from words union all select * from fuzzy
  ), completions as (
    -- One row per text however many kinds it came from; the strongest kind decides its weight.
    select key, max(tier) as tier,
           max(weight * case kind when 'query' then 3.0 when 'section' then 1.5 when 'brand' then 1.5 else 1.0 end) as weight
    from hits where kind in ('query', 'phrase', 'brand', 'section')
    group by key
  )
  select jsonb_build_object(
    'terms', coalesce((
      select jsonb_agg(jsonb_build_object('label', c.key) order by c.tier desc, c.weight desc, char_length(c.key), c.key)
      from (select * from completions order by tier desc, weight desc, char_length(key), key limit v_limit) c
    ), '[]'::jsonb),
    'products', coalesce((
      select jsonb_agg(jsonb_build_object('id', p.ref, 'name', p.label, 'slug', p.slug, 'image', p.image, 'price', p.price)
                       order by p.tier desc, (p.image is not null) desc, p.weight desc)
      from (
        select * from (
          select distinct on (h.ref) h.ref, h.label, h.slug, h.image, h.price, h.tier, h.weight
          from hits h
          where h.kind = 'phrase' and h.ref is not null and h.slug is not null
          order by h.ref, h.tier desc, h.weight desc
        ) d
        order by d.tier desc, (d.image is not null) desc, d.weight desc
        limit 4
      ) p
    ), '[]'::jsonb),
    'stores', coalesce((
      select jsonb_agg(jsonb_build_object('label', s.label, 'slug', s.ref) order by s.tier desc, s.weight desc, s.label)
      from (select * from hits where kind = 'store' order by tier desc, weight desc, label limit 4) s
    ), '[]'::jsonb),
    'categories', coalesce((
      select jsonb_agg(jsonb_build_object('label', c.label, 'id', c.ref) order by c.tier desc, c.label)
      from (select * from hits where kind = 'category' order by tier desc, label limit 3) c
    ), '[]'::jsonb),
    'corrected', v_corrected
  ) into v_out;
  return v_out;
end $$;

-- 7. Trending, as worked out on the hour ----------------------------------------------------------------------------------------
-- { computedAt, live, items: [{ term, count, hot, itemId, label, slug, image, price }] }. If the job has not run in 3 hours (or
-- never), the live count of 0039 is used, without pictures, and `live` says so.
create or replace function public.top_searches_hourly(p_limit integer default 10) returns jsonb
language sql stable security definer set search_path = public set statement_timeout = '3s' as $$
  select case
    when exists (select 1 from public.search_top_hourly where computed_at > now() - interval '3 hours') then
      jsonb_build_object(
        'computedAt', (select max(computed_at) from public.search_top_hourly),
        'live', false,
        'items', coalesce((
          select jsonb_agg(jsonb_build_object('term', t.term, 'count', t.searches, 'hot', t.hot, 'itemId', t.item_id, 'label', t.label,
                                              'slug', t.slug, 'image', t.image, 'price', t.price) order by t.rank)
          from (select * from public.search_top_hourly order by rank limit least(greatest(coalesce(p_limit, 10), 1), 20)) t
        ), '[]'::jsonb))
    else
      jsonb_build_object(
        'computedAt', now(),
        'live', true,
        'items', coalesce((
          select jsonb_agg(jsonb_build_object('term', t.term, 'count', t.count, 'hot', t.hot))
          from public.top_searches(least(greatest(coalesce(p_limit, 10), 1), 20)) t
        ), '[]'::jsonb))
  end
$$;

-- 8. The home feed's pool for one rotation hour --------------------------------------------------------------------------------
-- p_epoch = whole hours since 1970 (UTC). Only items created BEFORE that hour began, so the pool, and the order the endpoint
-- builds from it, is the same whenever and wherever it is asked for during the hour. Three parts, bounded whatever the size of
-- the catalogue, each driven by an index:
--   * featured: from every featured (Premium) shop, 12 of its 60 newest products, a different draw every hour;
--   * fresh: the newest products, at most 6 per shop (created_at index);
--   * discover: a slice of the long tail starting at an hourly pivot in id order (primary key), at most 4 per shop, so every
--     product, however old, comes round.
create or replace function public.products_feed_pool(p_epoch bigint, p_featured integer default 240, p_fresh integer default 360, p_discover integer default 480)
returns jsonb
language plpgsql stable security definer set search_path = public set statement_timeout = '8s' as $$
declare
  v_epoch bigint := greatest(coalesce(p_epoch, 0), 0);
  v_start timestamptz := to_timestamp(greatest(coalesce(p_epoch, 0), 0) * 3600);
  v_seed text := greatest(coalesce(p_epoch, 0), 0)::text;
  v_pivot uuid := md5('pivot:' || greatest(coalesce(p_epoch, 0), 0)::text)::uuid;
  v_nf integer := least(greatest(coalesce(p_featured, 240), 0), 1000);
  v_nr integer := least(greatest(coalesce(p_fresh, 360), 0), 1500);
  v_nd integer := least(greatest(coalesce(p_discover, 480), 0), 2000);
  v_featured uuid[];
  v_fresh uuid[];
  v_discover uuid[];
begin
  select coalesce(array_agg(f.id order by md5(v_seed || ':f:' || f.id::text)), '{}') into v_featured
  from (
    select x.id
    from public.businesses b
    cross join lateral (
      select n.id from (
        select i.id from public.items i
        where i.business_id = b.id and i.created_at < v_start
          and public.item_is_public(i.visible, i.draft, i.hidden_by_admin, i.removed_by_admin, i.availability)
        order by i.created_at desc
        limit 60
      ) n
      order by md5(v_seed || ':s:' || n.id::text)
      limit 12
    ) x
    where b.plan_key = 'premium' and public.business_is_visible(b)
    order by md5(v_seed || ':f:' || x.id::text)
    limit v_nf
  ) f;

  with newest as materialized (
    select i.id, i.business_id, i.created_at
    from public.items i
    where i.created_at < v_start
      and public.item_is_public(i.visible, i.draft, i.hidden_by_admin, i.removed_by_admin, i.availability)
    order by i.created_at desc, i.id
    limit v_nr * 4
  )
  select coalesce(array_agg(r.id order by r.created_at desc, r.id), '{}') into v_fresh
  from (
    select x.id, x.created_at from (
      select n.id, n.created_at, row_number() over (partition by n.business_id order by n.created_at desc, n.id) as per_shop
      from newest n join public.businesses b on b.id = n.business_id
      where public.business_is_visible(b)
    ) x
    where x.per_shop <= 6
    order by x.created_at desc, x.id
    limit v_nr
  ) r;

  with slice as materialized (
    (select i.id, i.business_id, 1 as part
     from public.items i
     where i.id >= v_pivot and i.created_at < v_start
       and public.item_is_public(i.visible, i.draft, i.hidden_by_admin, i.removed_by_admin, i.availability)
     order by i.id
     limit v_nd * 3)
    union all
    (select i.id, i.business_id, 2 as part
     from public.items i
     where i.id < v_pivot and i.created_at < v_start
       and public.item_is_public(i.visible, i.draft, i.hidden_by_admin, i.removed_by_admin, i.availability)
     order by i.id
     limit v_nd * 3)
  )
  select coalesce(array_agg(d.id order by d.part, d.id), '{}') into v_discover
  from (
    select x.id, x.part from (
      select s.id, s.part, row_number() over (partition by s.business_id order by s.part, s.id) as per_shop
      from slice s join public.businesses b on b.id = s.business_id
      where public.business_is_visible(b)
    ) x
    where x.per_shop <= 4
    order by x.part, x.id
    limit v_nd
  ) d;

  return public.products_by_ids(v_featured || v_fresh || v_discover)
    || jsonb_build_object('epoch', v_epoch, 'featured', cardinality(v_featured), 'fresh', cardinality(v_fresh), 'discover', cardinality(v_discover));
end $$;

