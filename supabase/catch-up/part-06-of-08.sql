-- 0128_search_index.sql
-- Search, type-ahead, trending searches and the home feed for a catalogue of millions of products.
--
-- Before this, product search, suggestions and the home grid all ran over an in-memory snapshot of the newest 10,000 products
-- (0043, 0127). That is right for a young marketplace, but past 10,000 an older product could not be found at all, and
-- suggestions only knew store names, categories and store tags (004201): typing "mi" never offered "milk". This migration is
-- the database half of the layered design in docs/catalog-scale.md:
--
--   1. search_key(): ONE immutable normal form for text (lower case, accents dropped, anything else a single space), so indexes
--      can be built on it. 0129 and 0130 build the two indexes on items, each on its own (create index).
--   2. search_terms (+ refresh_search_terms): a small dictionary of what a shopper can mean while typing: popular searches,
--      words and phrases from product names, brands, sections, stores, categories. Rebuilt in the background. Typing "mi" is
--      one index range scan on it, however many products exist, and it is also the vocabulary misspellings are corrected to.
--   3. search_product_candidates(): the products matching a query, found through the items indexes and BOUNDED (600 returned
--      by default, after looking at no more than 10,000 matches), in the products_snapshot shape, so /api/products ranks and
--      filters them with the same code as before. Nothing found: each unknown word is corrected once ("mlik" -> "milk").
--   4. search_suggest(): suggestions while typing, grouped (completions, products with a picture, stores, categories).
--   5. search_query_stats + search_top_hourly + top_searches_hourly(): the most searched terms, worked out once an hour (the
--      menu's "Trending" list), each with a picture from a matching product. Falls back to the live count of 0039.
--   6. products_feed_pool(): the home feed's candidates for one rotation hour: featured shops' products, the freshest products,
--      and a different slice of the long tail every hour. Chosen from the hour number alone, so every server and every cache
--      agrees on it, and nothing created during that hour joins it: a visitor paging through the feed never sees it shift.
--   7. refresh_search_rollups(): what the hourly pg_cron job runs (supabase/cron/schedule.sql), also listed in Admin > Automation.
--      Without the job everything still works: trending falls back to the live count and suggestions to the snapshot.
--
-- Every query on items is driven by an index (a full-text, trigram, created_at or primary-key index) and capped, so its cost does
-- not grow with the catalogue. Visitors can only read: every function they may call returns what the public views already show.
-- Additive and safe to run again.

create extension if not exists pg_trgm with schema extensions;
create extension if not exists unaccent with schema extensions;
create extension if not exists fuzzystrmatch with schema extensions;

-- 1. Normal form ---------------------------------------------------------------------------------------------------------------
-- IMMUTABLE so an index can be built on it. unaccent() itself is only STABLE because a dictionary could change; this pins the
-- dictionary by name, the documented way to index unaccented text. "Café Latté 500ML!" -> "cafe latte 500ml".
-- SECURITY DEFINER on purpose: it is part of two indexes on items, so EVERY write to items evaluates it, as whoever writes. Run
-- as its owner it can never fail for lack of a grant on the extensions schema, and it is never inlined into a caller's plan.
create or replace function public.search_key(p_text text) returns text
language sql immutable parallel safe security definer set search_path = pg_catalog, pg_temp as $$
  select btrim(regexp_replace(lower(extensions.unaccent('extensions.unaccent'::regdictionary, coalesce(p_text, ''))), '[^a-z0-9]+', ' ', 'g'))
$$;

-- What an item is found by: its name (weight A), its brand and section (weight B). 0130 indexes exactly this expression.
create or replace function public.item_search_doc(p_name text, p_brand text, p_section text) returns tsvector
language sql immutable parallel safe as $$
  select setweight(to_tsvector('simple'::regconfig, public.search_key(p_name)), 'A')
      || setweight(to_tsvector('simple'::regconfig, public.search_key(coalesce(p_brand, '') || ' ' || coalesce(p_section, ''))), 'B')
$$;

-- The words of a query, at most 8, plural endings trimmed ("speakers" -> "speaker", "batteries" -> "batter", "boxes" -> "box").
-- Every word is then matched as a PREFIX, so a trimmed word only ever finds more, never less.
create or replace function public.search_query_tokens(p_query text) returns text[]
language sql immutable parallel safe as $$
  select coalesce(array_agg(w order by n), '{}'::text[])
  from (
    select n, case
        when char_length(t) > 4 and t ~ 'ies$' then left(t, -3)
        when char_length(t) > 4 and t ~ '(sses|shes|ches|xes)$' then left(t, -2)
        when char_length(t) > 3 and t ~ '[^s]s$' then left(t, -1)
        else t
      end as w
    from unnest(string_to_array(public.search_key(left(coalesce(p_query, ''), 120)), ' ')) with ordinality as u(t, n)
    where char_length(t) >= 2 or t ~ '^[0-9]$'
    order by n
    limit 8
  ) x
$$;

-- Every word as a prefix, all required: "brook mil" finds "Brookside Milk 500ml". The words are [a-z0-9] only (search_key), and
-- quote_literal keeps them literal in any case.
create or replace function public.search_tsquery(p_tokens text[]) returns tsquery
language sql immutable parallel safe as $$
  select case when coalesce(cardinality(p_tokens), 0) = 0 then null
    else to_tsquery('simple'::regconfig, array_to_string(array(select quote_literal(t) || ':*' from unnest(p_tokens) t), ' & '))
  end
$$;

-- The items a visitor may see: the item half of public_items (0121); the store half is business_is_visible(). Written against
-- the tables so the planner can use the indexes on items. public_items is a security_barrier view, which would hide them.
create or replace function public.item_is_public(p_visible boolean, p_draft boolean, p_hidden boolean, p_removed boolean, p_availability text) returns boolean
language sql immutable parallel safe as $$
  select coalesce(p_visible, false) and not coalesce(p_draft, false) and not coalesce(p_hidden, false) and not coalesce(p_removed, false)
    and public.item_is_listed(p_availability)
$$;

-- 2. Tables --------------------------------------------------------------------------------------------------------------------
-- Popularity of searches, kept beyond the 2 days search_events holds: score = score * 0.97 + distinct searchers in the last hour,
-- once an hour, a half-life of about a day.
create table if not exists public.search_query_stats (
  term text primary key check (char_length(term) between 2 and 60),
  score real not null default 0,
  last_seen timestamptz not null default now()
);

-- The type-ahead dictionary. `key` is what is matched (search_key form) and, for completions, what is shown: shoppers are used to
-- lower-case suggestions. A 'phrase' row (a word or the start of a product name) also carries ONE example item (its name, store,
-- first picture and lowest price) for the picture rows of the suggestion list.
create table if not exists public.search_terms (
  kind text not null check (kind in ('query', 'phrase', 'brand', 'section', 'store', 'category')),
  key text not null check (char_length(key) between 1 and 80),
  label text not null,
  ref text,
  slug text,
  image text,
  price numeric(12, 2),
  weight real not null default 0,
  refreshed_at timestamptz not null default now(),
  primary key (kind, key)
);
-- "starts with": one range scan. text_pattern_ops makes LIKE 'mi%' indexable whatever the database collation is.
create index if not exists search_terms_prefix_idx on public.search_terms (key text_pattern_ops);
-- "a word in it starts with" and "looks like": trigrams.
create index if not exists search_terms_trgm_idx on public.search_terms using gin (key extensions.gin_trgm_ops);

-- The trending list, as last worked out (rank 1 = most searched).
create table if not exists public.search_top_hourly (
  rank smallint primary key check (rank between 1 and 50),
  term text not null,
  searches integer not null,
  hot boolean not null default false,
  item_id uuid,
  label text,
  slug text,
  image text,
  price numeric(12, 2),
  computed_at timestamptz not null default now()
);

