grant execute on function public.mpesa_stk_mark_sent(uuid, text, text, text), public.mpesa_stk_mark_error(uuid, text, text),
  public.mpesa_stk_apply_query(uuid, text, text, boolean), public.mpesa_stk_expire_stale() to service_role;

-- ---------------------------------------------------------------------------
-- 5. Settle a successful STK payment. The money goes to exactly the request's shop, for the request's purpose.
-- ---------------------------------------------------------------------------
create or replace function public.mpesa_stk_settle(p_id uuid, p_receipt text, p_amount numeric, p_phone text, p_time timestamptz,
  p_callback uuid, p_verification text, p_raw jsonb default '{}') returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare
  r public.mpesa_stk_requests;
  t public.mpesa_transactions;
  v_target uuid;
  v_new boolean := false;
  res jsonb;
begin
  select * into r from public.mpesa_stk_requests where id = p_id for update;
  if not found then raise exception 'request_not_found'; end if;
  if r.status = 'paid' then return jsonb_build_object('outcome', 'duplicate', 'duplicate', true, 'request_id', r.id); end if;
  v_target := coalesce(r.business_id, r.application_id);

  -- The Paybill (C2B) confirmation of the same payment may have arrived first (or be arriving right now): link to it,
  -- never credit twice. The receipt is unique in the ledger, so of two racing writers exactly one inserts.
  select * into t from public.mpesa_transactions where trans_id = p_receipt for update;
  if not found then
    insert into public.mpesa_transactions (trans_id, trans_time, amount_kes, account, payer_phone, msisdn_hash, short_code, raw, callback_id, channel, stk_request_id)
    values (p_receipt, coalesce(p_time, now()), p_amount, r.account_ref, nullif(p_phone, ''), public.msisdn_hash(coalesce(nullif(p_phone, ''), r.phone)),
            nullif(btrim(coalesce(p_raw ->> 'BusinessShortCode', '')), ''), coalesce(p_raw, '{}'), p_callback, 'stk', r.id)
    on conflict (trans_id) do nothing
    returning * into t;
    if t.id is null then
      select * into t from public.mpesa_transactions where trans_id = p_receipt for update;
    else
      v_new := true;
    end if;
  end if;
  if t.state <> 'needs_assignment' then
    -- Already credited (the Paybill confirmation matched it first). Nothing more to do with the money.
    res := jsonb_build_object('outcome', 'already_recorded', 'state', t.state,
      'business_id', t.business_id, 'application_id', t.application_id);
  elsif v_target is null then
    update public.mpesa_transactions set note = 'stk_target_deleted' where id = t.id;
    perform public.notify_admin('payment_unmatched', null, jsonb_build_object('code', p_receipt, 'amount', p_amount, 'note', 'stk_target_deleted'));
    res := jsonb_build_object('outcome', 'needs_assignment', 'note', 'stk_target_deleted');
  else
    if r.target_type = 'business' then
      -- The request says what the money is for; that beats any older intent.
      update public.businesses set pay_intent = case when r.purpose in ('upgrade', 'category_change') then
        jsonb_build_object('purpose', r.purpose, 'target_plan', r.target_plan, 'category', r.category_id, 'change_id', r.change_id, 'set_at', now()) end
       where id = r.business_id;
    end if;
    begin
      res := public.mpesa_credit_target(t.id, r.target_type, v_target, 'stk');
    exception when others then
      -- The money is recorded; the admin assigns it by hand with the request's shop as the suggestion.
      update public.mpesa_transactions set state = 'needs_assignment', note = 'credit_failed: ' || left(sqlerrm, 200),
        candidates = jsonb_build_array(public.mpesa_candidate(r.target_type, v_target, 'paid by phone prompt')) where id = t.id;
      perform public.notify_admin('payment_unmatched', null, jsonb_build_object('code', p_receipt, 'amount', p_amount, 'account', r.account_ref, 'note', 'credit_failed'));
      res := jsonb_build_object('outcome', 'needs_assignment', 'note', 'credit_failed');
    end;
  end if;
  if not v_new then
    update public.mpesa_transactions set channel = 'stk', stk_request_id = r.id where id = t.id;
  end if;

  update public.mpesa_stk_requests set status = 'paid', mpesa_receipt = p_receipt, paid_amount = p_amount, paid_phone = nullif(p_phone, ''),
    paid_at = coalesce(p_time, now()), verification = p_verification, tx_id = t.id, outcome = res, result_code = '0',
    callback_id = coalesce(p_callback, callback_id), completed_at = now()
   where id = r.id returning * into r;
  insert into public.audit_log (business_id, actor_id, actor_role, action, entity, entity_id, data)
  values (coalesce(r.business_id, (res ->> 'business_id')::uuid), null, 'system', 'stk_paid', 'mpesa_stk_request', r.id::text,
          jsonb_build_object('receipt', p_receipt, 'amount', p_amount, 'outcome', res ->> 'outcome', 'verification', p_verification));
  return res || jsonb_build_object('duplicate', false, 'request_id', r.id, 'code', p_receipt, 'amount', p_amount, 'account', r.account_ref,
    'application_id', coalesce(res ->> 'application_id', r.application_id::text));
end $$;
revoke all on function public.mpesa_stk_settle(uuid, text, numeric, text, timestamptz, uuid, text, jsonb) from public, anon, authenticated;
grant execute on function public.mpesa_stk_settle(uuid, text, numeric, text, timestamptz, uuid, text, jsonb) to service_role;

-- ---------------------------------------------------------------------------
-- 6. The STK callback. Stored raw first (mpesa_callbacks, kind 'stk'), then processed.
--    p_verification is what Safaricom's status query said about this CheckoutRequestID just before:
--      query_ok          the query confirms the payment
--      query_failed      the query says it did NOT go through -> never credited, held as disputed
--      query_unavailable the query could not be made (Safaricom busy); the callback, which came to our secret URL, decides
--      not_checked       verification is switched off
--      admin             an admin pressed Reprocess
-- ---------------------------------------------------------------------------
create or replace function public.mpesa_stk_parse(p_body jsonb) returns jsonb
language plpgsql stable as $$
declare
  s jsonb := coalesce(p_body -> 'Body' -> 'stkCallback', '{}'::jsonb);
  it jsonb;
  out jsonb := '{}'::jsonb;
  v_date text;
begin
  out := jsonb_build_object('checkout', nullif(btrim(s ->> 'CheckoutRequestID'), ''), 'merchant', nullif(btrim(s ->> 'MerchantRequestID'), ''),
    'code', nullif(btrim(s ->> 'ResultCode'), ''), 'desc', s ->> 'ResultDesc');
  for it in select * from jsonb_array_elements(case when jsonb_typeof(s -> 'CallbackMetadata' -> 'Item') = 'array' then s -> 'CallbackMetadata' -> 'Item' else '[]'::jsonb end)
  loop
    case it ->> 'Name'
      when 'Amount' then out := out || jsonb_build_object('amount', it ->> 'Value');
      when 'MpesaReceiptNumber' then out := out || jsonb_build_object('receipt', upper(btrim(it ->> 'Value')));
      -- Kept only when it is a whole number; a masked one (2547****149) is dropped rather than stored half.
      when 'PhoneNumber' then out := out || jsonb_build_object('phone', case
        when coalesce(it ->> 'Value', '') !~ '[*xX]' and regexp_replace(coalesce(it ->> 'Value', ''), '\D', '', 'g') ~ '^254[0-9]{9}$'
        then regexp_replace(it ->> 'Value', '\D', '', 'g') end);
      when 'TransactionDate' then v_date := it ->> 'Value';
      else null;
    end case;
  end loop;
  if v_date ~ '^[0-9]{14}$' then
    out := out || jsonb_build_object('time', to_char(make_timestamptz(substr(v_date, 1, 4)::int, substr(v_date, 5, 2)::int, substr(v_date, 7, 2)::int,
      substr(v_date, 9, 2)::int, substr(v_date, 11, 2)::int, substr(v_date, 13, 2)::int, 'Africa/Nairobi'), 'YYYY-MM-DD"T"HH24:MI:SSOF'));
  end if;
  return out;
end $$;

create or replace function public.mpesa_stk_process(p_callback uuid, p_verification text default 'not_checked') returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare
  cb public.mpesa_callbacks;
  p jsonb;
  r public.mpesa_stk_requests;
  v_amount numeric;
  v_receipt text;
  v_code text;
  t public.mpesa_transactions;
  res jsonb;
  v_note text;
begin
  select * into cb from public.mpesa_callbacks where id = p_callback for update;
  if not found then raise exception 'callback_not_found'; end if;
  if cb.processed then return jsonb_build_object('duplicate', true, 'outcome', 'already_processed'); end if;
  begin
    p := public.mpesa_stk_parse(cb.body);
    v_code := p ->> 'code';
    v_receipt := p ->> 'receipt';
    begin v_amount := (p ->> 'amount')::numeric; exception when others then v_amount := null; end;
    if p ->> 'checkout' is null or v_code is null then raise exception 'not_an_stk_callback'; end if;

    select * into r from public.mpesa_stk_requests where checkout_request_id = p ->> 'checkout' for update;
    if not found and v_code = '0' then
      -- Safaricom sent the prompt but we never learnt its CheckoutRequestID (the reply to our request was lost, or recording it
      -- failed). Same phone, same amount, within 15 minutes, still without an id: that is the one.
      select * into r from public.mpesa_stk_requests x
       where x.checkout_request_id is null and x.status in ('creating', 'error') and x.amount_kes = v_amount
         and x.phone = p ->> 'phone' and x.created_at > now() - interval '15 minutes'
       order by x.created_at desc limit 1 for update;
      if found then
        update public.mpesa_stk_requests set checkout_request_id = p ->> 'checkout', merchant_request_id = p ->> 'merchant',
          status = 'expired', sent_at = coalesce(sent_at, created_at), note = coalesce(note, 'matched by phone and amount') where id = r.id returning * into r;
      end if;
    end if;
    if r.id is null then
      -- Not one of ours. A success still holds real money: record it for an admin to assign, never drop it.
      if v_code = '0' and v_receipt ~ '^[A-Z0-9]{10}$' and v_amount > 0 then
        insert into public.mpesa_transactions (trans_id, trans_time, amount_kes, account, payer_phone, msisdn_hash, raw, callback_id, channel, note)
        values (v_receipt, coalesce((p ->> 'time')::timestamptz, now()), v_amount, null, p ->> 'phone', public.msisdn_hash(p ->> 'phone'), cb.body, cb.id, 'stk', 'stk_unknown_request')
        on conflict (trans_id) do nothing returning * into t;
        if t.id is not null then
          perform public.notify_admin('payment_unmatched', null, jsonb_build_object('code', v_receipt, 'amount', v_amount, 'note', 'stk_unknown_request'));
        end if;
      end if;
      update public.mpesa_callbacks set processed = true, trans_id = v_receipt, error = 'unknown_checkout_request' where id = cb.id;
      return jsonb_build_object('outcome', case when t.id is not null then 'needs_assignment' else 'ignored' end, 'note', 'unknown_checkout_request', 'duplicate', false);
    end if;

    if r.status = 'paid' then
      update public.mpesa_callbacks set processed = true, trans_id = coalesce(v_receipt, r.mpesa_receipt), error = 'duplicate' where id = cb.id;
      return jsonb_build_object('duplicate', true, 'outcome', 'duplicate', 'request_id', r.id);
    end if;

    if v_code <> '0' then
      -- Failed at Safaricom: cancelled, wrong PIN, not enough money, unreachable. No money moved.
      if r.status in ('creating', 'pending', 'expired') then
        update public.mpesa_stk_requests set status = 'failed', result_code = left(v_code, 40), result_desc = left(p ->> 'desc', 300),
          callback_id = cb.id, completed_at = now() where id = r.id returning * into r;
      elsif r.status = 'confirming' then
        -- The status query said paid, the callback says not: never guess, an admin checks the statement.
        update public.mpesa_stk_requests set status = 'disputed', result_code = left(v_code, 40), result_desc = left(p ->> 'desc', 300),
          note = 'Safaricom''s status query said paid but the callback says it failed', callback_id = cb.id where id = r.id returning * into r;
        perform public.notify_admin('payment_unmatched', r.business_id, jsonb_build_object('stk_request_id', r.id, 'amount', r.amount_kes, 'note', 'stk_disputed'));
      end if;
      update public.mpesa_callbacks set processed = true, error = null where id = cb.id;
      return jsonb_build_object('duplicate', false, 'outcome', 'failed', 'code', v_code, 'request_id', r.id, 'target_type', r.target_type,
        'business_id', r.business_id, 'application_id', r.application_id);
    end if;

    -- Success. Check it before any money is credited.
    v_note := case
      when p_verification = 'query_failed' then 'Safaricom''s status query says this payment did not go through'
      when v_receipt is null or v_receipt !~ '^[A-Z0-9]{10}$' then 'the receipt number is missing or malformed'
      when v_amount is null or v_amount <> r.amount_kes then format('the amount (%s) differs from the amount asked (%s)', coalesce(v_amount::text, 'none'), r.amount_kes)
      when exists (select 1 from public.mpesa_stk_requests x where x.mpesa_receipt = v_receipt and x.id <> r.id) then 'the receipt is already used by another request'
    end;
    if v_note is not null then
      update public.mpesa_stk_requests set status = 'disputed', note = v_note, result_code = '0', result_desc = left(p ->> 'desc', 300),
        paid_amount = v_amount, paid_phone = p ->> 'phone', callback_id = cb.id, verification = p_verification
       where id = r.id returning * into r;
      perform public.notify_admin('payment_unmatched', r.business_id, jsonb_build_object('stk_request_id', r.id, 'code', v_receipt, 'amount', v_amount,
        'note', 'stk_disputed', 'detail', v_note));
      update public.mpesa_callbacks set processed = true, trans_id = v_receipt, error = 'disputed' where id = cb.id;
      return jsonb_build_object('duplicate', false, 'outcome', 'disputed', 'note', v_note, 'request_id', r.id);
    end if;

    res := public.mpesa_stk_settle(r.id, v_receipt, v_amount, p ->> 'phone', (p ->> 'time')::timestamptz, cb.id, coalesce(p_verification, 'not_checked'), cb.body);
    update public.mpesa_callbacks set processed = true, trans_id = v_receipt, error = null where id = cb.id;
    return res;
  exception when others then
    update public.mpesa_callbacks set processed = false, error = sqlerrm, trans_id = nullif(v_receipt, '') where id = cb.id;
    return jsonb_build_object('outcome', 'error', 'error', sqlerrm, 'callback_id', cb.id);
  end;
end $$;

-- Store raw, then process. A failure callback is processed at once; a success callback is processed here only when the caller
-- has already checked it (p_verification given). pay-callback stores first (p_verification null), asks Safaricom, then calls
-- mpesa_stk_process, so even a crash between the two leaves the raw callback for the reconcile job or an admin.
create or replace function public.mpesa_stk_ingest(p_body jsonb, p_ip text default null, p_verification text default null) returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare
  cb uuid;
  p jsonb := public.mpesa_stk_parse(coalesce(p_body, '{}'::jsonb));
begin
  insert into public.mpesa_callbacks (kind, source_ip, body, trans_id)
  values ('stk', left(p_ip, 80), coalesce(p_body, '{}'::jsonb), p ->> 'receipt') returning id into cb;
  if p_verification is null and p ->> 'code' = '0' then
    return jsonb_build_object('needs_verification', true, 'callback_id', cb, 'checkout_request_id', p ->> 'checkout');
  end if;
  return public.mpesa_stk_process(cb, coalesce(p_verification, 'not_checked')) || jsonb_build_object('callback_id', cb);
end $$;

-- Raw STK callbacks that were stored but not processed yet (the reconcile job checks and processes them).
create or replace function public.mpesa_stk_unprocessed(p_limit integer default 20) returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object('callback_id', c.id, 'checkout_request_id', public.mpesa_stk_parse(c.body) ->> 'checkout')), '[]'::jsonb)
    from (select * from public.mpesa_callbacks
           -- Only callbacks never attempted (stored, then the function stopped). One that failed keeps its error for an admin
           -- (Payments > callbacks that could not be processed) instead of being retried, and e-mailed about, forever.
           where kind = 'stk' and not processed and dismissed_at is null and error is null and received_at < now() - interval '30 seconds'
           order by received_at limit greatest(1, least(coalesce(p_limit, 20), 100))) c
$$;

-- Prompts still waiting for an answer, oldest first, for the reconcile job to ask Safaricom about.
create or replace function public.mpesa_stk_to_query(p_limit integer default 20) returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object('id', s.id, 'checkout_request_id', s.checkout_request_id)), '[]'::jsonb)
    from (select * from public.mpesa_stk_requests
           where status in ('pending', 'expired') and checkout_request_id is not null
             and coalesce(sent_at, created_at) < now() - interval '45 seconds'
             and coalesce(sent_at, created_at) > now() - interval '1 day'
             and (last_query_at is null or last_query_at < now() - interval '2 minutes')
             and query_count < 8
           order by coalesce(sent_at, created_at) limit greatest(1, least(coalesce(p_limit, 20), 100))) s
$$;

revoke all on function public.mpesa_stk_parse(jsonb), public.mpesa_stk_process(uuid, text), public.mpesa_stk_ingest(jsonb, text, text),
  public.mpesa_stk_unprocessed(integer), public.mpesa_stk_to_query(integer) from public, anon, authenticated;
grant execute on function public.mpesa_stk_parse(jsonb), public.mpesa_stk_process(uuid, text), public.mpesa_stk_ingest(jsonb, text, text),
  public.mpesa_stk_unprocessed(integer), public.mpesa_stk_to_query(integer) to service_role;

-- Read one request for its owner. pay-stk-status checks the login or session, then calls this with the target id.
create or replace function public.mpesa_stk_get(p_id uuid, p_target uuid) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare r public.mpesa_stk_requests;
begin
  select * into r from public.mpesa_stk_requests where id = p_id and coalesce(business_id, application_id) = p_target;
  if not found then
    -- The application may have become a business since the request was made.
    select s.* into r from public.mpesa_stk_requests s join public.businesses b on b.application_id = s.application_id
     where s.id = p_id and b.id = p_target;
  end if;
  if r.id is null then return null; end if;
  return public.mpesa_stk_view(r) || jsonb_build_object('checkoutRequestId', r.checkout_request_id, 'queryCount', r.query_count,
    'lastQueryAt', r.last_query_at, 'targetType', r.target_type, 'applicationId', r.application_id, 'businessId', r.business_id);
end $$;
revoke all on function public.mpesa_stk_get(uuid, uuid) from public, anon, authenticated;
grant execute on function public.mpesa_stk_get(uuid, uuid) to service_role;

-- ---------------------------------------------------------------------------
-- 7. Paybill (C2B) confirmations: if it is the confirmation of a phone prompt (same account, same amount, same phone, within a
--    day), it goes to that request's shop and purpose. Otherwise exactly as before (0015).
--    The resolver also accepts the short form of an application reference used in prompts (2026ABC234).
-- ---------------------------------------------------------------------------
create or replace function public.mpesa_resolve(p_account text, p_hash text) returns jsonb
language plpgsql stable security definer set search_path = public, extensions as $$
declare
  k text := public.norm_key(p_account);
  a public.applications;
  b public.businesses;
  cands jsonb := '[]';
  narrowed jsonb;
  n integer;
  first_c jsonb;
begin
  if k = '' then
    return jsonb_build_object('note', 'no_account', 'candidates', public.mpesa_suggest('', p_hash));
  end if;

  select * into a from public.applications x where public.norm_key(x.reference_no) = k or public.norm_key(x.reference_no) = 'EPM' || k limit 1;
  if found then
    select * into b from public.businesses y where y.application_id = a.id and y.status <> 'deleted';
    if found then return jsonb_build_object('type', 'business', 'id', b.id, 'method', 'reference'); end if;
    if a.status in ('rejected', 'draft') then
      return jsonb_build_object('note', 'application_' || a.status, 'candidates', jsonb_build_array(public.mpesa_candidate('application', a.id, 'reference')));
    end if;
    return jsonb_build_object('type', 'application', 'id', a.id, 'method', 'reference');
  end if;

  select * into b from public.businesses y where public.norm_key(y.seller_id) = k and y.status <> 'deleted';
  if found then return jsonb_build_object('type', 'business', 'id', b.id, 'method', 'seller_id'); end if;

  select coalesce(jsonb_agg(c), '[]') into cands from (
    select public.mpesa_candidate('business', y.id, 'name') as c
      from public.businesses y where public.norm_key(y.name) = k and y.status <> 'deleted'
    union all
    select public.mpesa_candidate('application', x.id, 'name')
      from public.applications x
      where public.norm_key(x.business_name) = k and x.status not in ('rejected', 'activated', 'draft')
        and not exists (select 1 from public.businesses y where y.application_id = x.id)
  ) s;
  n := jsonb_array_length(cands);
  if n = 1 then
    first_c := cands -> 0;
    return jsonb_build_object('type', first_c ->> 'type', 'id', (first_c ->> 'id')::uuid, 'method', 'name');
  elsif n > 1 then
    select coalesce(jsonb_agg(c), '[]') into narrowed
      from jsonb_array_elements(cands) c
      where public.entity_has_phone(c ->> 'type', (c ->> 'id')::uuid, p_hash);
    if jsonb_array_length(narrowed) = 1 then
      first_c := narrowed -> 0;
      return jsonb_build_object('type', first_c ->> 'type', 'id', (first_c ->> 'id')::uuid, 'method', 'name+phone');
    end if;
    return jsonb_build_object('note', 'ambiguous_name', 'candidates', cands);
  end if;

  return jsonb_build_object('note', 'no_match', 'candidates', public.mpesa_suggest(k, p_hash));
end $$;

create or replace function public.mpesa_process(p_callback uuid) returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare
  cb public.mpesa_callbacks;
  body jsonb;
  v_id text;
  v_amount numeric;
  v_msisdn text;
  v_hash text;
  v_plain text;
  v_name text;
  v_time timestamptz;
  t public.mpesa_transactions;
  s public.mpesa_stk_requests;
  r jsonb;
  res jsonb;
begin
  select * into cb from public.mpesa_callbacks where id = p_callback for update;
  if not found then raise exception 'callback_not_found'; end if;
  if cb.kind = 'stk' then return public.mpesa_stk_process(p_callback, 'admin'); end if;
  body := cb.body;
  begin
    v_id := upper(btrim(coalesce(body ->> 'TransID', '')));
    if v_id = '' then raise exception 'missing_trans_id'; end if;
    v_amount := nullif(btrim(coalesce(body ->> 'TransAmount', '')), '')::numeric;
    if v_amount is null or v_amount <= 0 then raise exception 'invalid_amount'; end if;
    begin
      v_time := make_timestamptz(substr(body ->> 'TransTime', 1, 4)::int, substr(body ->> 'TransTime', 5, 2)::int, substr(body ->> 'TransTime', 7, 2)::int,
                                 substr(body ->> 'TransTime', 9, 2)::int, substr(body ->> 'TransTime', 11, 2)::int, substr(body ->> 'TransTime', 13, 2)::int, 'Africa/Nairobi');
    exception when others then v_time := null; end;

    v_msisdn := btrim(coalesce(body ->> 'MSISDN', ''));
    if v_msisdn ~* '^[0-9a-f]{64}$' then
      v_hash := lower(v_msisdn);
    elsif regexp_replace(v_msisdn, '\D', '', 'g') ~ '^254[0-9]{9}$' and v_msisdn !~ '[*xX]' then
      v_plain := regexp_replace(v_msisdn, '\D', '', 'g');
      v_hash := public.msisdn_hash(v_plain);
    end if;
    v_name := btrim(concat_ws(' ', nullif(btrim(body ->> 'FirstName'), ''), nullif(btrim(body ->> 'MiddleName'), ''), nullif(btrim(body ->> 'LastName'), '')));

    insert into public.mpesa_transactions (trans_id, trans_time, amount_kes, account, msisdn_hash, payer_phone, payer_name, short_code, raw, callback_id)
    values (v_id, v_time, v_amount, nullif(btrim(body ->> 'BillRefNumber'), ''), v_hash, v_plain, nullif(v_name, ''),
            nullif(btrim(body ->> 'BusinessShortCode'), ''), body, cb.id)
    on conflict (trans_id) do nothing
    returning * into t;
    if t.id is null then
      -- Already recorded: a Safaricom retry, or the STK callback of the same payment got here first. Keep the payer's name.
      update public.mpesa_transactions set payer_name = coalesce(payer_name, nullif(v_name, '')), msisdn_hash = coalesce(msisdn_hash, v_hash)
       where trans_id = v_id;
      update public.mpesa_callbacks set processed = true, trans_id = v_id, error = 'duplicate' where id = cb.id;
      return jsonb_build_object('duplicate', true, 'code', v_id);
    end if;

    -- The confirmation of a phone prompt whose own callback has not come (yet)?
    select * into s from public.mpesa_stk_requests x
     where x.mpesa_receipt is null
       and (x.status in ('pending', 'confirming', 'expired') or (x.status = 'failed' and x.created_at > now() - interval '2 hours'))
       and x.account_ref = public.norm_key(t.account) and x.amount_kes = t.amount_kes
       and x.created_at > now() - interval '1 day'
       and (v_hash is null or public.msisdn_hash(x.phone) = v_hash)
     order by x.created_at desc limit 1 for update skip locked;
    if found then
      res := public.mpesa_stk_settle(s.id, v_id, v_amount, v_plain, v_time, cb.id, 'c2b', body);
      update public.mpesa_callbacks set processed = true, trans_id = v_id, error = null where id = cb.id;
      return res || jsonb_build_object('duplicate', false, 'code', v_id, 'amount', v_amount, 'account', t.account);
    end if;

    r := public.mpesa_resolve(t.account, v_hash);
    if r ? 'type' then
      begin
        res := public.mpesa_credit_target(t.id, r ->> 'type', (r ->> 'id')::uuid, r ->> 'method');
      exception when others then
        update public.mpesa_transactions set state = 'needs_assignment', note = 'credit_failed: ' || left(sqlerrm, 200),
          candidates = jsonb_build_array(public.mpesa_candidate(r ->> 'type', (r ->> 'id')::uuid, 'matched but could not be credited')) where id = t.id;
        perform public.notify_admin('payment_unmatched', null, jsonb_build_object('code', v_id, 'amount', v_amount, 'account', t.account, 'note', 'credit_failed'));
        res := jsonb_build_object('outcome', 'needs_assignment', 'note', 'credit_failed');
      end;
    else
      update public.mpesa_transactions set state = 'needs_assignment', candidates = coalesce(r -> 'candidates', '[]'), note = r ->> 'note' where id = t.id;
      perform public.notify_admin('payment_unmatched', null, jsonb_build_object('code', v_id, 'amount', v_amount, 'account', t.account, 'note', r ->> 'note'));
      res := jsonb_build_object('outcome', 'needs_assignment', 'note', r ->> 'note');
    end if;
    update public.mpesa_callbacks set processed = true, trans_id = v_id, error = null where id = cb.id;
    return res || jsonb_build_object('duplicate', false, 'code', v_id, 'amount', v_amount, 'account', t.account);
  exception when others then
    update public.mpesa_callbacks set processed = false, error = sqlerrm, trans_id = nullif(v_id, '') where id = cb.id;
    return jsonb_build_object('outcome', 'error', 'error', sqlerrm, 'callback_id', cb.id);
  end;
end $$;
revoke all on function public.mpesa_process(uuid) from public, anon, authenticated;
grant execute on function public.mpesa_process(uuid) to service_role;

