create or replace view public.admin_stk_requests as
select
  s.id, s.status, s.purpose, s.months, s.amount_kes, s.unit_price, s.credit_used, s.phone, s.account_ref,
  coalesce(b.name, a.business_name, 'Deleted') as business_name,
  coalesce(b.seller_id, a.reference_no) as reference,
  coalesce(b.town, a.town) as town,
  s.target_type, s.application_id, coalesce(s.business_id, (select y.id from public.businesses y where y.application_id = s.application_id limit 1)) as business_id,
  s.mpesa_receipt, s.paid_amount, s.paid_phone, s.result_code, s.result_desc, public.mpesa_stk_message(s.status, s.result_code) as message,
  s.verification, s.note, s.outcome ->> 'outcome' as outcome, s.initiated_by, s.query_count,
  s.created_at, s.sent_at, s.completed_at, s.checkout_request_id
from public.mpesa_stk_requests s
left join public.businesses b on b.id = s.business_id
left join public.applications a on a.id = s.application_id
where public.is_admin();
revoke all on public.admin_stk_requests from anon;
grant select on public.admin_stk_requests to authenticated;

-- An admin checked a disputed prompt against the M-Pesa statement: credit it (with the receipt and amount from the statement),
-- or close it. Owner and finance only, audited.
create or replace function public.admin_stk_resolve(p_id uuid, p_action text, p_receipt text default null, p_amount numeric default null, p_reason text default null) returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare
  r public.mpesa_stk_requests;
  v_receipt text := upper(btrim(coalesce(p_receipt, '')));
  res jsonb;
begin
  if not public.has_role(array['owner', 'finance']) then raise exception 'forbidden' using errcode = '42501'; end if;
  if char_length(btrim(coalesce(p_reason, ''))) < 3 then raise exception 'reason_required'; end if;
  select * into r from public.mpesa_stk_requests where id = p_id for update;
  if not found then raise exception 'request_not_found'; end if;
  if r.status not in ('disputed', 'confirming', 'expired') then raise exception 'already_handled'; end if;
  if p_action = 'credit' then
    if v_receipt !~ '^[A-Z0-9]{10}$' then raise exception 'invalid_receipt'; end if;
    if p_amount is null or p_amount <= 0 then raise exception 'invalid_amount'; end if;
    res := public.mpesa_stk_settle(r.id, v_receipt, p_amount, r.paid_phone, now(), r.callback_id, 'admin', '{}'::jsonb);
  elsif p_action = 'close' then
    update public.mpesa_stk_requests set status = 'failed', note = left(btrim(p_reason), 300), completed_at = now() where id = r.id;
    res := jsonb_build_object('outcome', 'closed');
  else
    raise exception 'invalid_action';
  end if;
  perform public.write_audit(r.business_id, 'stk_' || p_action, 'mpesa_stk_request', r.id::text,
    jsonb_build_object('receipt', nullif(v_receipt, ''), 'amount', p_amount, 'reason', btrim(p_reason), 'was', r.status));
  return res;
end $$;
revoke all on function public.admin_stk_resolve(uuid, text, text, numeric, text) from public, anon;
grant execute on function public.admin_stk_resolve(uuid, text, text, numeric, text) to authenticated;

-- The Payments list: expected price from business_unit_price, and how the money came (paybill, stk, manual).
create or replace view public.admin_payment_queue as
select * from (
select
  'tx:' || t.id::text                                  as row_key,
  t.id                                                 as tx_id,
  case
    when t.state = 'needs_assignment' then 'needs_assignment'
    when t.state = 'ignored' then 'ignored'
    when t.state = 'applied' then case when p.source = 'auto' then 'renewed' else 'confirmed' end
    when a.status = 'payment_confirming' then 'awaiting_confirmation'
    else 'part_paid'
  end                                                  as status,
  coalesce(a.reference_no, b.seller_id)                as reference,
  coalesce(a.business_name, b.name, 'No matching business') as business_name,
  coalesce(a.town, b.town)                             as town,
  t.account                                            as account,
  t.amount_kes                                         as amount_kes,
  case when a.id is not null then public.mpesa_price(a) when b.id is not null then public.business_unit_price(b) end as expected_kes,
  coalesce(a.credit_kes, b.credit_kes)                 as credit_kes,
  case when a.id is not null and a.status = 'payment_confirming' then
    least(floor(a.credit_kes / nullif(public.mpesa_price(a), 0))::integer,
          coalesce((select (s.value #>> '{}')::integer from public.site_settings s where s.key = 'max_prepay_months'), 12)) end as suggested_months,
  t.trans_id                                           as mpesa_code,
  t.payer_phone                                        as phone,
  t.payer_name                                         as payer_name,
  t.short_code                                         as paybill_number,
  p.receipt_no                                         as receipt_no,
  coalesce(t.trans_time, t.created_at)                 as at,
  a.id                                                 as application_id,
  coalesce(b.id, t.business_id)                        as business_id,
  a.status                                             as app_status,
  a.payment_code                                       as app_payment_code,
  t.candidates                                         as candidates,
  t.note                                               as note,
