-- A Safaricom number in the form Daraja wants: 2547XXXXXXXX or 2541XXXXXXXX. Accepts 0712..., +254712..., 254712..., 712...
create or replace function public.mpesa_stk_phone(p text) returns text
language sql immutable as $$
  select '254' || m[1]
    from regexp_match(regexp_replace(coalesce(p, ''), '[^0-9+]', '', 'g'), '^(?:\+?254|0)?((?:7|1)[0-9]{8})$') as m
$$;

-- The account reference shown on the payer's phone and M-Pesa SMS. STK Push allows at most 12 characters, so an application
-- reference (EPM-2026-ABC234, 13 without hyphens) drops its constant "EPM" (2026ABC234). mpesa_resolve accepts both forms.
create or replace function public.mpesa_stk_account(p_ref text) returns text
language plpgsql immutable as $$
declare k text := public.norm_key(p_ref);
begin
  if char_length(k) > 12 and left(k, 3) = 'EPM' then k := substr(k, 4); end if;
  return right(k, 12);
end $$;

-- What the payer is told, for each state and Safaricom result code. Shown as is by the applicant page and the seller portal.
create or replace function public.mpesa_stk_message(p_status text, p_code text) returns text
language sql immutable as $$
  select case p_status
    when 'creating' then 'Sending the payment request to your phone.'
    when 'pending' then 'A payment request is on your phone. Enter your M-Pesa PIN there to pay.'
    when 'confirming' then 'Safaricom says you paid. We are waiting for the receipt, which takes a moment. Do not pay again.'
    when 'paid' then 'Thank you. Your payment is recorded.'
    when 'expired' then 'We did not get an answer from your phone in time. If you entered your PIN, the payment is still recorded as soon as Safaricom confirms it. Otherwise, try again.'
    when 'error' then 'We could not send the payment request to your phone. Try again in a minute, or pay with Paybill instead.'
    when 'disputed' then 'We are checking this payment with Safaricom. We will confirm it shortly; do not pay again.'
    when 'failed' then case p_code
      when '1032' then 'You cancelled the M-Pesa request. Nothing was charged.'
      when '1' then 'Your M-Pesa balance is not enough for this payment. Nothing was charged.'
      when '2001' then 'The M-Pesa PIN was not correct. Nothing was charged. Try again.'
      when '1037' then 'We could not reach your phone. Check that it is on and has network, then try again.'
      when '1019' then 'The request expired before it was answered. Try again.'
      when '1001' then 'Another M-Pesa request is open on this phone. Finish or cancel it, then try again.'
      when '1025' then 'Safaricom could not send the request. Try again in a minute.'
      when '9999' then 'Safaricom could not send the request. Try again in a minute.'
      else 'The payment did not go through. Nothing was charged. Try again.'
    end
    else 'Unknown payment state.'
  end
$$;

