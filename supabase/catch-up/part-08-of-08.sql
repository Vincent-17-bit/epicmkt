-- 0136_mpesa_stk_push.sql
-- M-Pesa STK Push ("Pay now": a PIN prompt on the payer's phone) and one price for every payment path.
--
-- 1. One price. The monthly price of a live business is the CURRENT price of its plan in its category (plans.price_kes).
--    Before this migration the seller's page and the payment quote used the plan price, but the automatic crediting used
--    businesses.monthly_price, which was written once at activation and never changed (not on a plan price change, not on an
--    upgrade to Premium, not on a category change). A seller who paid exactly the amount shown could be told "KES 100 more is
--    needed", and an upgraded seller was credited months at the Standard rate. Now:
--      * business_unit_price(b) is the only answer to "what does one month cost this shop", used by the quote, the crediting,
--        the STK Push amount and the admin list;
--      * a plan price change reaches every live business at its next payment (time already paid for is not touched), and
--        each affected seller gets an in-app note;
--      * businesses.monthly_price is kept equal to that price (on insert, on a plan or category change, and on a plan price
--        change) so the admin totals (MRR, expiry radar) stay right. It is a mirror, never the source.
--    An admin's per-application "charge a different amount" override still applies to that application's first payment.
--
-- 2. STK Push. The amount is ALWAYS worked out here, from the database, at the moment the payer presses Pay; the browser only
--    says what is being paid for (first month, renewal, upgrade, category change) and for how many months. The request is
--    recorded before Safaricom is called. Safaricom's answer (the STK callback) is stored raw first, like every C2B callback,
--    then matched by its CheckoutRequestID to exactly one request, so the payment always reaches the shop that asked for it,
--    for the purpose it was asked for. A success is credited through the same ledger as Paybill payments (mpesa_transactions
--    -> credit -> whole months), so activation, renewals, upgrades, part payments and overpayments all behave the same way.
--    The receipt number is unique in the ledger, so a Paybill (C2B) confirmation for the same payment, a Safaricom retry or a
--    late callback can never credit it twice, in whichever order they arrive.
--    A success callback whose amount differs from what was asked, or that Safaricom's own status query says failed, is never
--    credited: it is held as "disputed" for an admin. Nothing is ever dropped.

