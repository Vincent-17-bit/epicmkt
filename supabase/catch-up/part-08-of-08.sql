create or replace function public.business_unit_price(p_b public.businesses) returns integer
language sql stable security definer set search_path = public as $$
  select coalesce(
    (select p.price_kes from public.plans p where p.category_id = p_b.category_id and p.plan_key = p_b.plan_key),
    nullif(p_b.monthly_price, 0))
$$;
revoke all on function public.business_unit_price(public.businesses) from public, anon;
grant execute on function public.business_unit_price(public.businesses) to authenticated, service_role;

