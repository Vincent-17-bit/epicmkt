// Builds supabase/data/categories_from_code.sql: every shop category defined in client/src/data/categories.js, for a database
// that is missing some of them (a category added to the code without a migration never reaches the admin, seller or client
// sites, which all read the database). scripts/categories-from-code.test.mjs regenerates it and compares.
//
//   node scripts/gen-categories-from-code.mjs          writes the file
//
// Every insert is "do nothing on conflict": a category or plan that is already in the database is left exactly as the admin
// set it (name, group, on/off, prices, benefits). Only what is missing is added: the category switched on, both plans priced
// by its tier, like the other seeded categories. Safe to run any number of times.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { categories } from "../client/src/data/categories.js";
import { planRows, TIER_PLANS } from "../client/src/config/plans.seed.js";

const here = dirname(fileURLToPath(import.meta.url));
export const CATEGORIES_FILE = join(here, "..", "supabase", "data", "categories_from_code.sql");

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;

export function categoriesSql() {
  const plans = categories.flatMap((c) => planRows(c.id, c.tier));
  const tiers = Object.entries(TIER_PLANS).map(([t, p]) => `${t} ${p.standard.price}/${p.premium.price}`).join(", ");
  return [
    "-- Every shop category the code knows (client/src/data/categories.js), added to the database where it is missing.",
    `-- ${categories.length} categories, ${plans.length} plans. Prices for a missing plan come from its tier (Standard/Premium KES: ${tiers}).`,
    "-- Nothing that is already in the database is changed: an admin's names, groups, on/off switches and prices stay as they are.",
    "-- Safe to run twice. Run it after the migrations, in the Supabase SQL editor. Generated by scripts/gen-categories-from-code.mjs.",
    "",
    "insert into public.categories (id, name, grp, icon, tier, sort, active, template, extra_docs)",
    "values",
    categories.map((c, i) => `  (${q(c.id)}, ${q(c.name)}, ${q(c.group)}, ${q(c.icon)}, ${q(c.tier)}, ${(i + 1) * 10}, true, ${j(c.keyFields)}, ${j(c.extraDocs ?? [])})`).join(",\n"),
    "on conflict (id) do nothing;",
    "",
    "insert into public.plans (category_id, plan_key, price_kes, items_limit, top_benefits, features, badge)",
    "values",
    plans.map((r) => `  (${q(r.category_id)}, ${q(r.plan_key)}, ${r.price_kes}, ${r.items_limit ?? "null"}, ${j(r.top_benefits)}, ${j(r.features)}, ${r.badge ? q(r.badge) : "null"})`).join(",\n"),
    "on conflict (category_id, plan_key) do nothing;",
    "",
    "-- What the sites will show: every category that is switched on and has both plans priced.",
    "select count(*) filter (where c.active) as switched_on,",
    "       count(*) filter (where c.active and (select count(*) from public.plans p where p.category_id = c.id and p.price_kes > 0) = 2) as shown_with_prices,",
    "       count(*) as in_database",
    "  from public.categories c;",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(dirname(CATEGORIES_FILE), { recursive: true });
  writeFileSync(CATEGORIES_FILE, categoriesSql());
  console.log(`wrote ${CATEGORIES_FILE}`);
}
