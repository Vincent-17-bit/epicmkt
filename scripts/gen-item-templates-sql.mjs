// Generates supabase/seed-item-templates.sql from shared/src/seller/item-templates.js.
//   node scripts/gen-item-templates-sql.mjs           writes the file
//   node scripts/gen-item-templates-sql.mjs --check   fails if the committed file is out of date
// The SQL sets categories.item_template ONLY. It does not touch names, templates, plans, prices or legal text, so it is
// safe to run on a live project where admins have already edited prices (unlike `npm run seed`, which overwrites them).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ITEM_TEMPLATES } from "../shared/src/seller/item-templates.js";

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "supabase", "seed-item-templates.sql");

export function buildSql(templates = ITEM_TEMPLATES) {
  const ids = Object.keys(templates);
  const updates = ids.map((id) => `update public.categories set item_template = $j$${JSON.stringify(templates[id])}$j$::jsonb where id = '${id.replace(/'/g, "''")}';`);
  return [
    "-- GENERATED by scripts/gen-item-templates-sql.mjs from shared/src/seller/item-templates.js. Do not edit by hand.",
    "--",
    "-- Sets public.categories.item_template ONLY. It does not touch category names, business templates, plans, prices or",
    "-- legal text, so it is safe on a live project where prices have been edited. Safe to run again.",
    "-- Run in the Supabase SQL editor after migration 0007 has been applied (`supabase db push`).",
    "",
    ...updates,
    "",
    "-- Check 1: ids above that do not exist as categories (should return no rows).",
    `select v.id as missing_category from (values ${ids.map((id) => `('${id.replace(/'/g, "''")}')`).join(", ")}) as v(id)`,
    "where not exists (select 1 from public.categories c where c.id = v.id);",
    "",
    "-- Check 2: how many categories now have item fields.",
    "select count(*) as categories, count(*) filter (where jsonb_array_length(item_template) > 0) as with_item_fields from public.categories;",
    "",
  ].join("\n");
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const sql = buildSql();
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(out, "utf8"); } catch { /* missing file fails below */ }
    if (current !== sql) {
      console.error("supabase/seed-item-templates.sql is out of date. Run: node scripts/gen-item-templates-sql.mjs");
      process.exit(1);
    }
    console.log("seed-item-templates.sql is up to date");
  } else {
    writeFileSync(out, sql);
    console.log(`wrote ${out}`);
  }
}
