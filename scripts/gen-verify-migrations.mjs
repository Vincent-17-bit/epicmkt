import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "supabase/migrations";
const files = readdirSync(dir).filter((f) => /^\d{4}_.*\.sql$/.test(f)).sort();
const strip = (sql) => sql.replace(/\/\*[\s\S]*?\*\//g, "").replace(/--[^\n]*/g, "");
const unq = (s) => s.replace(/"/g, "").replace(/^public\./, "").toLowerCase();
const id = String.raw`((?:public\.)?"?[a-zA-Z_][\w$]*"?)`;

const found = new Map();
const add = (kind, name, extra, mig) => found.set(`${kind}|${name}|${extra}`, { kind, name, extra, mig });
const drop = (kind, name, extra = "") => found.delete(`${kind}|${name}|${extra}`);

for (const file of files) {
  const mig = file.slice(0, 4);
  const sql = strip(readFileSync(join(dir, file), "utf8"));
  const dollar = [];
  const body = sql.replace(/\$([a-zA-Z_]*)\$[\s\S]*?\$\1\$/g, (m) => (dollar.push(m), "$$BODY$$"));
  for (const m of body.matchAll(new RegExp(String.raw`create\s+table\s+(?:if\s+not\s+exists\s+)?${id}`, "gi"))) add("table", unq(m[1]), "", mig);
  for (const m of body.matchAll(new RegExp(String.raw`create\s+(?:or\s+replace\s+)?(?:materialized\s+)?view\s+${id}`, "gi"))) add("view", unq(m[1]), "", mig);
  for (const m of body.matchAll(new RegExp(String.raw`create\s+(?:or\s+replace\s+)?function\s+${id}\s*\(`, "gi"))) add("function", unq(m[1]), "", mig);
  for (const m of body.matchAll(new RegExp(String.raw`create\s+type\s+${id}`, "gi"))) add("type", unq(m[1]), "", mig);
  for (const m of body.matchAll(new RegExp(String.raw`create\s+(?:unique\s+)?index\s+(?:concurrently\s+)?(?:if\s+not\s+exists\s+)?${id}`, "gi"))) add("index", unq(m[1]), "", mig);
  for (const m of body.matchAll(new RegExp(String.raw`create\s+(?:or\s+replace\s+)?trigger\s+${id}`, "gi"))) add("trigger", unq(m[1]), "", mig);
  for (const m of body.matchAll(new RegExp(String.raw`create\s+policy\s+("[^"]+"|[\w$]+)\s+on\s+${id}`, "gi"))) add("policy", m[1].replace(/"/g, ""), unq(m[2]), mig);
  for (const m of body.matchAll(new RegExp(String.raw`alter\s+table\s+(?:if\s+exists\s+)?(?:only\s+)?${id}([\s\S]*?);`, "gi"))) {
    const t = unq(m[1]);
    for (const c of m[2].matchAll(new RegExp(String.raw`add\s+column\s+(?:if\s+not\s+exists\s+)?${id}`, "gi"))) add("column", unq(c[1]), t, mig);
    for (const c of m[2].matchAll(new RegExp(String.raw`drop\s+column\s+(?:if\s+exists\s+)?${id}`, "gi"))) drop("column", unq(c[1]), t);
    for (const c of m[2].matchAll(new RegExp(String.raw`rename\s+column\s+${id}\s+to\s+${id}`, "gi"))) { drop("column", unq(c[1]), t); add("column", unq(c[2]), t, mig); }
    const r = m[2].match(new RegExp(String.raw`^\s*rename\s+to\s+${id}`, "i"));
    if (r) { drop("table", t); drop("view", t); add("table", unq(r[1]), "", mig); }
  }
  for (const m of body.matchAll(new RegExp(String.raw`drop\s+table\s+(?:if\s+exists\s+)?${id}`, "gi"))) drop("table", unq(m[1]));
  for (const m of body.matchAll(new RegExp(String.raw`drop\s+(?:materialized\s+)?view\s+(?:if\s+exists\s+)?${id}`, "gi"))) drop("view", unq(m[1]));
  for (const m of body.matchAll(new RegExp(String.raw`drop\s+function\s+(?:if\s+exists\s+)?${id}`, "gi"))) drop("function", unq(m[1]));
  for (const m of body.matchAll(new RegExp(String.raw`drop\s+index\s+(?:concurrently\s+)?(?:if\s+exists\s+)?${id}`, "gi"))) drop("index", unq(m[1]));
  for (const m of body.matchAll(new RegExp(String.raw`drop\s+trigger\s+(?:if\s+exists\s+)?${id}`, "gi"))) drop("trigger", unq(m[1]));
  for (const m of body.matchAll(new RegExp(String.raw`drop\s+type\s+(?:if\s+exists\s+)?${id}`, "gi"))) drop("type", unq(m[1]));
  for (const m of body.matchAll(new RegExp(String.raw`drop\s+policy\s+(?:if\s+exists\s+)?("[^"]+"|[\w$]+)\s+on\s+${id}`, "gi"))) drop("policy", m[1].replace(/"/g, ""), unq(m[2]));
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rows = [...found.values()].sort((a, b) => a.mig.localeCompare(b.mig) || a.kind.localeCompare(b.kind) || a.name.localeCompare(b.name));
const values = rows.map((r) => `  (${q(r.mig)}, ${q(r.kind)}, ${q(r.name)}, ${q(r.extra)})`).join(",\n");

const out = `-- Generated by: node scripts/gen-verify-migrations.mjs   (${files.length} migration files, ${rows.length} objects)
-- Paste into the Supabase SQL editor and run. It lists every object a migration creates that is NOT in the database.
-- No rows = every migration's tables, views, functions, types, indexes, triggers, policies and columns are there.
-- A migration number with rows was not applied, or only partly. An object a later migration renamed through code this
-- check cannot read can show here by mistake: look at the name before re-running anything.
with expected(mig, kind, name, extra) as (
values
${values}
), present as (
  select 'table' as kind, c.relname::text as name, '' as extra from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relkind in ('r','p')
  union all select 'view', c.relname, '' from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relkind in ('v','m')
  union all select 'function', p.proname, '' from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public'
  union all select 'type', t.typname, '' from pg_type t join pg_namespace n on n.oid = t.typnamespace where n.nspname = 'public'
  union all select 'index', i.indexname, '' from pg_indexes i where i.schemaname = 'public'
  union all select 'trigger', t.tgname, '' from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and not t.tgisinternal
  union all select 'policy', p.policyname, p.tablename from pg_policies p where p.schemaname = 'public'
  union all select 'column', col.column_name, col.table_name from information_schema.columns col where col.table_schema = 'public'
)
select e.mig as migration, e.kind, e.name, e.extra as on_table
from expected e
where not exists (select 1 from present p where p.kind = e.kind and p.name = e.name and p.extra = e.extra)
order by e.mig, e.kind, e.name;
`;
writeFileSync("supabase/verify-migrations.sql", out);
console.log(`${files.length} files, ${rows.length} objects -> supabase/verify-migrations.sql`);
