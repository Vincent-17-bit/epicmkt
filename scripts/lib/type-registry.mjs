// The product-type registry shipped to shared: every seeded type with its department and kind. Rendered from scripts/seeds, so the file in
// shared cannot drift from the seeds without scripts/type-registry.test.mjs failing.
import { ALL_TYPES } from "../seeds/index.mjs";

export const REGISTRY_PATH = "shared/src/productType/registry.generated.js";

export function renderRegistry(types = ALL_TYPES) {
  const rows = [...types].sort((a, b) => (a.id < b.id ? -1 : 1)).map((t) => `  ${JSON.stringify(t.id)}: [${JSON.stringify(t.departmentId ?? null)}, ${JSON.stringify(t.kind)}],`);
  return [
    "// GENERATED by `node scripts/generate-type-registry.mjs` from scripts/seeds. Do not edit by hand.",
    "// product type id -> [department id, kind]. Kind is \"good\", \"service\" or \"package\" (a package is a service-like offer).",
    "export const TYPE_REGISTRY = Object.freeze({",
    ...rows,
    "});",
    ""
  ].join("\n");
}
